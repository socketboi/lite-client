// Capture the pinned Framer's independent header/trailer declaration limits.
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"golang.org/x/net/http2"
	"golang.org/x/net/http2/hpack"
)

func main() {
	if len(os.Args) != 2 {
		panic("expected output header path")
	}
	type sample struct {
		name   string
		fields []hpack.HeaderField
	}
	f := func(name, value string) hpack.HeaderField { return hpack.HeaderField{Name: name, Value: value} }
	status := f(":status", "200")
	cases := []sample{
		{"separate", []hpack.HeaderField{status, f("x", strings.Repeat("a", 40)), f("trailer", strings.Repeat("q", 80))}},
		{"comma amplification", []hpack.HeaderField{status, f("trailer", ",,,,,")}},
		{"empty declaration", []hpack.HeaderField{status, f("trailer", "")}},
		{"ordinary overflow", []hpack.HeaderField{status, f("x", strings.Repeat("a", 100))}},
		{"exact trailer budget", []hpack.HeaderField{status, f("trailer", strings.Repeat("q", 96))}},
		{"trailer overflow", []hpack.HeaderField{status, f("trailer", strings.Repeat("q", 97))}},
		{"repeated declaration", []hpack.HeaderField{status, f("trailer", "a"), f("trailer", "b"), f("x", strings.Repeat("a", 40))}},
	}
	large := sample{name: "fragment budgets"}
	large.fields = append(large.fields, status)
	for j := 0; j < 5; j++ {
		value := make([]byte, 80)
		for i := range value {
			value[i] = byte(33 + (i*37+j*13)%90)
		}
		large.fields = append(large.fields, f(fmt.Sprintf("x%d", j), string(value)))
	}
	cases = append(cases, large)
	var out strings.Builder
	out.WriteString("/* Generated by the pinned x/net HTTP/2 Framer; do not edit. */\n")
	out.WriteString("#ifdef LC_HEADER_BUDGET_CASES\n")
	var rows []string
	for index, test := range cases {
		var block bytes.Buffer
		encoder := hpack.NewEncoder(&block)
		for _, field := range test.fields {
			if err := encoder.WriteField(field); err != nil {
				panic(err)
			}
		}
		var wire bytes.Buffer
		if err := http2.NewFramer(&wire, nil).WriteHeaders(http2.HeadersFrameParam{StreamID: 1, EndHeaders: true, BlockFragment: block.Bytes()}); err != nil {
			panic(err)
		}
		framer := http2.NewFramer(nil, &wire)
		framer.MaxHeaderListSize = 128
		framer.ReadMetaHeaders = hpack.NewDecoder(4096, nil)
		frame, err := framer.ReadFrame()
		failed, truncated := 0, 0
		if err != nil {
			failed = 1
		} else if frame.(*http2.MetaHeadersFrame).Truncated {
			truncated = 1
		}
		fmt.Fprintf(&out, "static const uint8_t budget_block_%d[] = {", index)
		for _, b := range block.Bytes() {
			fmt.Fprintf(&out, "%d,", b)
		}
		out.WriteString("};\n")
		rows = append(rows, fmt.Sprintf("{%q, budget_block_%d, sizeof budget_block_%d, %d, %d}", test.name, index, index, failed, truncated))
	}
	out.WriteString("static const struct budget_case { const char *name; const uint8_t *block; size_t len; int error, truncated; } budget_cases[] = {\n")
	out.WriteString(strings.Join(rows, ",\n"))
	out.WriteString("\n};\n")
	out.WriteString("#endif\n")
	// Retake the existing ten-megabyte continuation boundary from the reference.
	var initial bytes.Buffer
	if err := hpack.NewEncoder(&initial).WriteField(f(":status", "302")); err != nil {
		panic(err)
	}
	var longWire bytes.Buffer
	writer := http2.NewFramer(&longWire, nil)
	if err := writer.WriteHeaders(http2.HeadersFrameParam{StreamID: 1, BlockFragment: initial.Bytes()}); err != nil {
		panic(err)
	}
	firstLen := longWire.Len()
	block := append([]byte{0, 1, 'x', 0x7f, 0x81, 0x7c}, bytes.Repeat([]byte{'a'}, 16000)...)
	for n := 0; n < 700; n++ {
		if err := writer.WriteContinuation(1, n == 699, block); err != nil {
			panic(err)
		}
	}
	reader := bytes.NewReader(longWire.Bytes())
	framer := http2.NewFramer(nil, reader)
	framer.MaxHeaderListSize = 10 * 1024 * 1024
	framer.ReadMetaHeaders = hpack.NewDecoder(4096, nil)
	if _, err := framer.ReadFrame(); err == nil {
		panic("oversized continuation chain was accepted")
	}
	consumed := longWire.Len() - reader.Len() - firstLen
	if consumed <= 0 || consumed%(9+len(block)) != 0 {
		panic("partial reference continuation capture")
	}
	fmt.Fprintf(&out, "static const unsigned reference_header_continuation_cutoff = %du;\n", consumed/(9+len(block)))
	if err := os.WriteFile(os.Args[1], []byte(out.String()), 0644); err != nil {
		panic(err)
	}
}
