// Generates the compact HPACK/QPACK Huffman tables in src/quic/huffman_table.h.
//
// The code itself is RFC 7541 appendix B, and HTTP/3 reuses it unchanged (RFC 9204 section 5).
// The source of the numbers here is vendor/nghttp3, so that the table this client ships and the
// table the cross-check in test/h3 decodes against cannot drift apart: they are the same 257 codes.
//
// What is NOT taken from nghttp3 is its decoder. That is a 256-state transition machine —
// nghttp3_qpack_huffman_data.c is 115 KB of source and lands as about 16 KB of tables — and it buys
// speed we have no use for: this client Huffman-codes a few hundred bytes per connection, once. The
// canonical decoder in huffman.c does the same job from 2 KB by walking bits, because the code is
// canonical: sort the symbols by (length, code) and the codes of each length are consecutive.
//
// That property is not assumed. It is checked below, and a table that broke it would stop the
// build rather than produce a decoder that is quietly wrong for a handful of characters.
//
//	cd tools/hpack && go run . > ../../src/quic/huffman_table.h
package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
)

type sym struct {
	value int
	nbits int
	code  uint32 // aligned to the least significant bit
}

func main() {
	src, err := os.ReadFile("../../vendor/nghttp3/lib/nghttp3_qpack_huffman_data.c")
	if err != nil {
		fail(err)
	}

	// The table opens with `const nghttp3_qpack_huffman_sym huffman_sym_table[] = {` and its
	// entries are `{nbits, 0x...U}` pairs. Anything after the closing brace is the decoder's own
	// state machine, which we do not read.
	body := string(src)
	start := regexp.MustCompile(`huffman_sym_table\[\]\s*=\s*\{`).FindStringIndex(body)
	if start == nil {
		fail(fmt.Errorf("no huffman_sym_table in nghttp3"))
	}
	body = body[start[1]:]
	if end := regexp.MustCompile(`\n\};`).FindStringIndex(body); end != nil {
		body = body[:end[0]]
	}

	entry := regexp.MustCompile(`\{\s*(\d+)\s*,\s*0x([0-9A-Fa-f]+)U?\s*\}`)
	matches := entry.FindAllStringSubmatch(body, -1)
	if len(matches) != 257 {
		fail(fmt.Errorf("expected 257 codes, found %d", len(matches)))
	}

	syms := make([]sym, 257)
	for i, m := range matches {
		nbits, err := strconv.Atoi(m[1])
		if err != nil {
			fail(err)
		}
		// nghttp3 stores the code aligned to the most significant bit of a 32-bit word.
		msb, err := strconv.ParseUint(m[2], 16, 64)
		if err != nil {
			fail(err)
		}
		if nbits < 5 || nbits > 30 {
			fail(fmt.Errorf("symbol %d has an implausible length %d", i, nbits))
		}
		syms[i] = sym{value: i, nbits: nbits, code: uint32(msb >> (32 - nbits))}
	}

	// Canonical order: by length, then by code.
	ordered := make([]sym, len(syms))
	copy(ordered, syms)
	sort.Slice(ordered, func(a, b int) bool {
		if ordered[a].nbits != ordered[b].nbits {
			return ordered[a].nbits < ordered[b].nbits
		}
		return ordered[a].code < ordered[b].code
	})

	const maxBits = 30
	count := make([]int, maxBits+1)
	firstCode := make([]uint32, maxBits+1)
	firstIndex := make([]int, maxBits+1)
	for _, s := range ordered {
		count[s.nbits]++
	}
	// The canonical relation, and the whole reason the small decoder works: the first code of each
	// length is the first code of the previous length, plus how many there were, shifted up one.
	next := uint32(0)
	idx := 0
	for l := 1; l <= maxBits; l++ {
		next <<= 1
		firstCode[l] = next
		firstIndex[l] = idx
		next += uint32(count[l])
		idx += count[l]
	}

	// Verified, not assumed: every symbol's code has to be exactly the one the canonical rule
	// assigns it. If nghttp3's table ever stopped satisfying this, the decoder built from it would
	// return the wrong character for some inputs and be right for most — the worst way to be wrong.
	for i, s := range ordered {
		want := firstCode[s.nbits] + uint32(i-firstIndex[s.nbits])
		if s.code != want {
			fail(fmt.Errorf("symbol %d breaks canonical order: code %x, canonical %x",
				s.value, s.code, want))
		}
	}

	out := os.Stdout
	fmt.Fprint(out, `/* HPACK/QPACK Huffman codes, RFC 7541 appendix B.
 *
 * GENERATED by tools/hpack from vendor/nghttp3 — do not edit. Committed rather than built, so that
 * building this client needs a C compiler and nothing else.
 *
 * Two views of the same 257 codes: by symbol, which is what encoding needs, and in canonical order,
 * which is what decoding needs. Together they cost about 2 KB of flash and replace a 16 KB state
 * machine that would have been faster than anything here can measure. */

`)

	fmt.Fprintf(out, "#define LC_HUFF_MIN_BITS %d\n", ordered[0].nbits)
	fmt.Fprintf(out, "#define LC_HUFF_MAX_BITS %d\n\n", ordered[len(ordered)-1].nbits)
	fmt.Fprintf(out, "/* The symbol that means \"end of string\", which may never appear in one. */\n")
	fmt.Fprintf(out, "#define LC_HUFF_EOS 256\n\n")

	fmt.Fprint(out, "static const uint32_t huff_code[257] = {\n")
	writeU32(out, func(i int) uint32 { return syms[i].code }, 257, 8)
	fmt.Fprint(out, "};\n\nstatic const uint8_t huff_nbits[257] = {\n")
	writeU32(out, func(i int) uint32 { return uint32(syms[i].nbits) }, 257, 16)
	fmt.Fprint(out, "};\n\n/* Symbols sorted by (length, code). */\nstatic const uint16_t huff_ordered[257] = {\n")
	writeU32(out, func(i int) uint32 { return uint32(ordered[i].value) }, 257, 12)

	fmt.Fprint(out, "};\n\n/* Indexed by code length. */\nstatic const uint32_t huff_first_code[LC_HUFF_MAX_BITS + 1] = {\n")
	writeU32(out, func(i int) uint32 { return firstCode[i] }, maxBits+1, 8)
	fmt.Fprint(out, "};\n\nstatic const uint16_t huff_first_index[LC_HUFF_MAX_BITS + 1] = {\n")
	writeU32(out, func(i int) uint32 { return uint32(firstIndex[i]) }, maxBits+1, 12)
	fmt.Fprint(out, "};\n\nstatic const uint16_t huff_count[LC_HUFF_MAX_BITS + 1] = {\n")
	writeU32(out, func(i int) uint32 { return uint32(count[i]) }, maxBits+1, 12)
	fmt.Fprint(out, "};\n")
}

func writeU32(f *os.File, at func(int) uint32, n, perLine int) {
	for i := 0; i < n; i++ {
		if i%perLine == 0 {
			fmt.Fprint(f, "    ")
		}
		fmt.Fprintf(f, "%#x,", at(i))
		if i%perLine == perLine-1 || i == n-1 {
			fmt.Fprint(f, "\n")
		} else {
			fmt.Fprint(f, " ")
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "tools/hpack:", err)
	os.Exit(1)
}
