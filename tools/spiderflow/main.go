// The WINDOW_UPDATE frames the reference's spider sends while it reads a page, computed with the
// reference's own readers: `io.ReadAll(resp.Body)`
// (vendor/Xray-core/transport/internet/reality/reality.go:268) over x/net's body, which is wrapped
// in its gzipReader when the answer is gzip — and that is gzip.NewReader over a bufio.Reader of
// 4096 bytes. What each Read of the body returns decides what inflow.add is handed
// (vendor/x-net/http2/transport.go:2230-2279), and inflow.add, copied here verbatim from
// vendor/x-net/http2/flow.go:36-56, decides when a WINDOW_UPDATE goes out.
//
// ONE ASSUMPTION, shared with the C side and named there too: the reader drains what has arrived
// before the next frame arrives. Go's reader is a goroutine woken by the frame; a page's frames
// come a network round trip apart; the decompression of four kilobytes is microseconds. The body
// here hands out one frame at a time and only when the previous one is used up.
package main

import (
	"bytes"
	"compress/gzip"
	"fmt"
	"io"
	"math/rand"
	"strings"
)

const inflowMinRefresh = 4 << 10

// Verbatim from vendor/x-net/http2/flow.go:17-56, the panics aside.
type inflow struct {
	avail  int32
	unsent int32
}

func (f *inflow) init(n int32) { f.avail = n }

func (f *inflow) add(n int) (connAdd int32) {
	unsent := int64(f.unsent) + int64(n)
	f.unsent = int32(unsent)
	if f.unsent < inflowMinRefresh && f.unsent < f.avail {
		return 0
	}
	f.avail += f.unsent
	f.unsent = 0
	return int32(unsent)
}

// The body as the transport hands it over, one DATA frame at a time.
type framed struct {
	frames [][]byte
	cur    []byte
	conn   inflow
	stream inflow
	out    []string
}

func (b *framed) Read(p []byte) (int, error) {
	if len(b.cur) == 0 {
		if len(b.frames) == 0 {
			return 0, io.EOF
		}
		// A frame arrives: the flow-control windows are taken from as processData takes them
		// (vendor/x-net/http2/transport.go:2383-2388). No padding in these frames.
		b.cur = b.frames[0]
		b.frames = b.frames[1:]
		b.conn.avail -= int32(len(b.cur))
		b.stream.avail -= int32(len(b.cur))
	}
	n := copy(p, b.cur)
	b.cur = b.cur[n:]
	c := b.conn.add(n)
	s := b.stream.add(n)
	if c != 0 || s != 0 {
		b.out = append(b.out, fmt.Sprintf("{ %d, %d }", c, s))
	}
	return n, nil
}

type gzipReader struct {
	body io.Reader
	zr   *gzip.Reader
	zerr error
}

// The shape of x/net's gzipReader: the gzip reader is made on the first Read, over the body itself.
func (gz *gzipReader) Read(p []byte) (int, error) {
	if gz.zerr != nil {
		return 0, gz.zerr
	}
	if gz.zr == nil {
		gz.zr, gz.zerr = gzip.NewReader(gz.body)
		if gz.zerr != nil {
			return 0, gz.zerr
		}
	}
	return gz.zr.Read(p)
}

func page(rng *rand.Rand, n int) []byte {
	var b strings.Builder
	b.WriteString("<!doctype html><html><head><title>t</title></head><body>")
	for b.Len() < n {
		fmt.Fprintf(&b, "<p><a href=\"/p%d\">%x</a> %x</p>\n", rng.Intn(1000), rng.Int63(), rng.Int63())
	}
	b.WriteString("</body></html>")
	return []byte(b.String())
}

func split(body []byte, sizes []int) [][]byte {
	var out [][]byte
	for i := 0; len(body) > 0; i++ {
		n := sizes[i%len(sizes)]
		if n > len(body) {
			n = len(body)
		}
		out = append(out, body[:n])
		body = body[n:]
	}
	return out
}

func main() {
	rng := rand.New(rand.NewSource(1))
	fmt.Println("/* Generated by tools/spiderflow from Go's own io.ReadAll, bufio and gzip, and x/net's inflow. */")
	type vcase struct {
		name  string
		gz    bool
		size  int
		split []int
	}
	cases := []vcase{
		{"gzip, 16 KiB frames", true, 400000, []int{16384}},
		{"gzip, uneven frames", true, 300000, []int{1000, 5000, 16384, 7, 4096, 12000}},
		{"gzip, small frames", true, 60000, []int{1400}},
		{"plain, 16 KiB frames", false, 200000, []int{16384}},
		{"plain, uneven frames", false, 150000, []int{1000, 5000, 16384, 7, 4096, 12000}},
		{"plain, small frames", false, 30000, []int{1400}},
		{"plain, tiny", false, 3000, []int{16384}},
	}
	var defs, table strings.Builder
	table.WriteString("static const struct {\n    const char *name;\n    int gzip;\n    unsigned nframes;\n" +
		"    const unsigned *frames;\n    unsigned nupdates;\n    const unsigned (*updates)[2];\n" +
		"    const unsigned char *body;\n    unsigned body_len;\n} spiderflow[] = {\n")
	for i, c := range cases {
		body := page(rng, c.size)
		if c.gz {
			var z bytes.Buffer
			w := gzip.NewWriter(&z)
			w.Write(body)
			w.Close()
			body = z.Bytes()
		}
		// The body itself, which the fetch now reads through Go's own gzip reader (core/gozip).
		fmt.Fprintf(&defs, "static const unsigned char spiderflow_body_%d[] = {", i)
		for j, x := range body {
			if j%24 == 0 {
				defs.WriteString("\n   ")
			}
			fmt.Fprintf(&defs, "%d,", x)
		}
		defs.WriteString("\n};\n")
		frames := split(body, c.split)
		b := &framed{frames: frames}
		b.conn.init(1<<30 + 65535)
		b.stream.init(4 << 20)
		var r io.Reader = b
		if c.gz {
			r = &gzipReader{body: b}
		}
		if _, err := io.ReadAll(r); err != nil {
			panic(err)
		}
		fmt.Fprintf(&defs, "static const unsigned spiderflow_frames_%d[] = {", i)
		for j, f := range frames {
			if j%12 == 0 {
				defs.WriteString("\n   ")
			}
			fmt.Fprintf(&defs, " %d,", len(f))
		}
		defs.WriteString("\n};\n")
		fmt.Fprintf(&defs, "static const unsigned spiderflow_updates_%d[][2] = {", i)
		for j, u := range b.out {
			if j%6 == 0 {
				defs.WriteString("\n   ")
			}
			fmt.Fprintf(&defs, " %s,", u)
		}
		if len(b.out) == 0 {
			defs.WriteString(" { 0, 0 }") // ISO C has no empty initialiser; nupdates says there are none
		}
		defs.WriteString("\n};\n")
		g := 0
		if c.gz {
			g = 1
		}
		fmt.Fprintf(&table, "    { %q, %d, %d, spiderflow_frames_%d, %d, spiderflow_updates_%d, spiderflow_body_%d, %d },\n",
			c.name, g, len(frames), i, len(b.out), i, i, len(body))
	}
	table.WriteString("};\n")
	fmt.Print(defs.String())
	fmt.Print(table.String())
}
