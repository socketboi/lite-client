// What the reference hashes for a Certificate message — certificateMsgTLS13's own unmarshal and
// marshal, run rather than transcribed (vendor/utls/handshake_messages.go:1525-1657): transcriptMsg
// writes `msg.marshal()` for it, not the bytes that came (:2009-2023). Writes
// test/cert/remarshal_vectors.h, which test/cert holds lc_cert13_remarshal to.
//
// A TEST OF uTLS's OWN PACKAGE, because the message type is unexported: this file is dropped into a
// copy of vendor/utls and run with `go test`, as tools/certcompread is. FROZEN, NOT BUILT BY THE
// GATE: `make check` runs with --network none and the package's modules have to be fetched.
// Regenerate in the build image, from the repository root:
//
//	docker run --rm -v "$PWD:/repo" lc-build:local sh -c 'cp -r /repo/vendor/utls /tmp/u \
//	  && cp /repo/tools/certremarshal/certremarshal_vectors_test.go /tmp/u/ \
//	  && cd /tmp/u && REMARSHAL_OUT=/repo/test/cert/remarshal_vectors.h \
//	     go test -run TestRemarshalVectors -count=1 .'
//
// The messages are the shapes where marshal differs from what came: an extension it does not know,
// the staple and the SCTs in the other order, two SCT extensions, two staples, extensions on a
// certificate that is not the leaf — and the canonical shape, where it must not differ.
package tls

import (
	"fmt"
	"os"
	"strings"
	"testing"
)

func rmU16(v int) []byte { return []byte{byte(v >> 8), byte(v)} }
func rmU24(v int) []byte { return []byte{byte(v >> 16), byte(v >> 8), byte(v)} }

func rmExt(typ int, body []byte) []byte {
	return append(append(rmU16(typ), rmU16(len(body))...), body...)
}

func rmOCSP(staple []byte) []byte {
	return rmExt(5, append(append([]byte{1}, rmU24(len(staple))...), staple...))
}

func rmSCT(scts ...[]byte) []byte {
	var list []byte
	for _, s := range scts {
		list = append(append(list, rmU16(len(s))...), s...)
	}
	return rmExt(18, append(rmU16(len(list)), list...))
}

type rmEntry struct {
	cert []byte
	exts [][]byte
}

// The message whole, header included, as a peer would send it.
func rmMessage(entries ...rmEntry) []byte {
	var list []byte
	for _, e := range entries {
		var exts []byte
		for _, x := range e.exts {
			exts = append(exts, x...)
		}
		list = append(append(list, rmU24(len(e.cert))...), e.cert...)
		list = append(append(list, rmU16(len(exts))...), exts...)
	}
	body := append([]byte{0}, append(rmU24(len(list)), list...)...)
	return append(append([]byte{typeCertificate}, rmU24(len(body))...), body...)
}

func rmBytes(n int, seed byte) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = seed + byte(i*7)
	}
	return b
}

func TestRemarshalVectors(t *testing.T) {
	leaf, mid, root := rmBytes(300, 0x30), rmBytes(200, 0x51), rmBytes(90, 0x77)
	staple, staple2 := rmBytes(40, 0x11), rmBytes(25, 0x99)
	sct1, sct2, sct3 := rmBytes(20, 0x21), rmBytes(33, 0x42), rmBytes(7, 0x63)
	unknown := rmExt(0x1234, rmBytes(9, 0x05))
	empty := rmExt(0x4455, nil)

	cases := []struct {
		name string
		msg  []byte
	}{
		{"canonical: staple then SCTs on the leaf, nothing on the rest",
			rmMessage(rmEntry{leaf, [][]byte{rmOCSP(staple), rmSCT(sct1, sct2)}}, rmEntry{mid, nil})},
		{"no extensions at all, three certificates",
			rmMessage(rmEntry{leaf, nil}, rmEntry{mid, nil}, rmEntry{root, nil})},
		{"an unknown extension on the leaf, between the two it keeps",
			rmMessage(rmEntry{leaf, [][]byte{rmOCSP(staple), unknown, rmSCT(sct1)}})},
		{"the SCTs before the staple",
			rmMessage(rmEntry{leaf, [][]byte{rmSCT(sct1, sct2), rmOCSP(staple)}}, rmEntry{mid, nil})},
		{"two SCT extensions",
			rmMessage(rmEntry{leaf, [][]byte{rmSCT(sct1), rmSCT(sct2, sct3)}})},
		{"two staples",
			rmMessage(rmEntry{leaf, [][]byte{rmOCSP(staple), rmOCSP(staple2)}})},
		{"extensions on the intermediate, known and not",
			rmMessage(rmEntry{leaf, [][]byte{rmSCT(sct3)}}, rmEntry{mid, [][]byte{rmOCSP(staple), unknown, empty}})},
		{"only unknown extensions on the leaf",
			rmMessage(rmEntry{leaf, [][]byte{empty, unknown}}, rmEntry{root, nil})},
	}

	var out strings.Builder
	out.WriteString("/* Generated by tools/certremarshal from vendor/utls's own certificateMsgTLS13.\n * Do not edit. */\n\n")
	out.WriteString("static const struct {\n    const char *name;\n    const unsigned char *in;\n    unsigned in_len;\n    const unsigned char *out;\n    unsigned out_len;\n} remarshal_vectors[] = {\n")
	for _, c := range cases {
		var m certificateMsgTLS13
		if !m.unmarshal(c.msg) {
			t.Fatalf("%s: does not unmarshal", c.name)
		}
		got, err := m.marshal()
		if err != nil {
			t.Fatalf("%s: marshal: %v", c.name, err)
		}
		fmt.Fprintf(&out, "    { %q,\n      (const unsigned char *)\"%s\", %d,\n      (const unsigned char *)\"%s\", %d },\n",
			c.name, rmHex(c.msg[4:]), len(c.msg)-4, rmHex(got), len(got))
	}
	out.WriteString("};\n")

	path := os.Getenv("REMARSHAL_OUT")
	if path == "" {
		t.Fatal("REMARSHAL_OUT is not set")
	}
	if err := os.WriteFile(path, []byte(out.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}

func rmHex(b []byte) string {
	var s strings.Builder
	for _, x := range b {
		fmt.Fprintf(&s, "\\x%02x", x)
	}
	return s.String()
}
