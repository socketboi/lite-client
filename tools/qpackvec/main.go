// The Hysteria2 authentication request's field section, encoded by qpack itself — the encoder
// quic-go's HTTP/3 client writes it with (vendor/qpack, the v0.6.0 vendor/quic-go/go.mod requires).
// The fields and their order are quic-go's request writer's for hysteria's request
// (vendor/quic-go/http3/request_writer.go:139-190): the four pseudo-headers, the three hysteria
// headers in the order Go's map walk gave them, then content-length, accept-encoding and user-agent.
// test/h3 builds the same input with lc_h3_auth_request_with and demands the same bytes.
//
//	go run . > qpack_vectors.h
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/quic-go/qpack"
)

const alphabet = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

type vcase struct {
	password string
	rx       string
	padLen   int
	order    [3]int
}

func pad(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteByte(alphabet[(i*7+3)%len(alphabet)])
	}
	return b.String()
}

func cstr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 0x20 || c >= 0x7f || c == '"' || c == '\\' || c == '?' {
			fmt.Fprintf(&b, "\\%03o", c)
		} else {
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func main() {
	cases := []vcase{
		{"secret-password", "0", 256, [3]int{0, 1, 2}},
		{"", "0", 300, [3]int{1, 2, 0}},
		{"p@ss:w/rd#1 ~Ж", "12345678", 2047, [3]int{2, 0, 1}},
		{"x", "100000000", 1024, [3]int{0, 1, 2}},
		{"AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA", "0", 777, [3]int{1, 2, 0}},
	}
	w := os.Stdout
	fmt.Fprintln(w, "/* Generated by tools/qpackvec from vendor/qpack; do not edit. */")
	fmt.Fprintln(w, "static const struct {")
	fmt.Fprintln(w, "    const char   *password, *rx;")
	fmt.Fprintln(w, "    unsigned      pad_len;")
	fmt.Fprintln(w, "    unsigned      order[3];")
	fmt.Fprintln(w, "    unsigned      len;")
	fmt.Fprintln(w, "    const uint8_t *bytes;")
	fmt.Fprintln(w, "} qpack_auth[] = {")
	for _, c := range cases {
		var buf bytes.Buffer
		e := qpack.NewEncoder(&buf)
		hy := [3][2]string{
			{"hysteria-auth", c.password},
			{"hysteria-cc-rx", c.rx},
			{"hysteria-padding", pad(c.padLen)},
		}
		fields := [][2]string{{":authority", "hysteria"}, {":method", "POST"}, {":path", "/auth"}, {":scheme", "https"}}
		for _, k := range c.order {
			fields = append(fields, hy[k])
		}
		fields = append(fields, [2]string{"content-length", "0"}, [2]string{"accept-encoding", "gzip"},
			[2]string{"user-agent", "quic-go HTTP/3"})
		for _, f := range fields {
			if err := e.WriteField(qpack.HeaderField{Name: f[0], Value: f[1]}); err != nil {
				panic(err)
			}
		}
		b := buf.Bytes()
		fmt.Fprintf(w, "    { %s, %s, %d, { %d, %d, %d }, %d, (const uint8_t[]){", cstr(c.password), cstr(c.rx),
			c.padLen, c.order[0], c.order[1], c.order[2], len(b))
		for i, x := range b {
			if i%16 == 0 {
				fmt.Fprint(w, "\n        ")
			}
			fmt.Fprintf(w, "0x%02x,", x)
		}
		fmt.Fprintln(w, " } },")
	}
	fmt.Fprintln(w, "};")
	fmt.Fprintf(w, "static const char qpack_pad_alphabet[] = %s;\n", cstr(alphabet))
}
