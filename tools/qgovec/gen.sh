#!/bin/sh
# Vectors from quic-go itself, for test/ngpatch and test/hybbr: the patched ngtcp2 is held to what
# the reference COMPUTES on the same inputs, not to what a comment says it computes.
#
# Each *_test.go here is laid into the vendored quic-go package it names through `go test -overlay`
# — the package's own tests are hidden the same way, so only the generator compiles — and run
# there, where quic-go's internal types are in reach. vendor/ is never written: an overlay changes
# what the compiler reads, not the tree.
#
# The connection-ID manager and the flow controllers live in quic-go's root package, and that
# package needs uTLS and golang.org/x/net, which the build container does not hold offline. So their
# four files are laid, unchanged, into a package of their own (internal/qgovec, which does not
# exist in the tree) beside the generator; they import nothing but quic-go's internal packages and
# the standard library. And every build gets internal/utils/rand.go replaced by utils_rand.go, whose
# "random" bytes are one byte repeated: see that file.
#
#	sh tools/qgovec/gen.sh OUT.h          (from the repository root, with Go)
set -e
out=$1
[ -n "$out" ] || { echo "usage: gen.sh OUT.h" >&2; exit 2; }
here=$(cd "$(dirname "$0")" && pwd)
q=$(cd vendor/quic-go && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# package dir (relative to quic-go) = generator file
pairs="internal/qgovec quic_test.go
internal/protocol protocol_test.go
internal/wire wire_test.go
internal/congestion congestion_test.go
internal/ackhandler ackhandler_test.go"
rootfiles="conn_id_manager.go flow_controller_base.go flow_controller_connection.go flow_controller_stream.go crypto_stream.go frame_sorter.go streams_map_incoming.go streams_map_outgoing.go sni.go"

{
	for f in $rootfiles; do
		printf '"%s/internal/qgovec/%s":"%s/%s"\n' "$q" "$f" "$q" "$f"
	done
	printf '"%s/internal/utils/rand.go":"%s/utils_rand.go"\n' "$q" "$here"
	printf '%s\n' "$pairs" | while read -r dir file; do
		for t in "$q/$dir"/*_test.go; do
			[ -e "$t" ] || continue
			printf '"%s":""\n' "$t"
		done
		printf '"%s/%s/zz_qgovec_test.go":"%s/%s"\n' "$q" "$dir" "$here" "$file"
	done
} | sed '$!s/$/,/; 1s/^/{"Replace":{/; $s/$/}}/' > "$tmp/ov.json"

{
	echo "/* Generated by tools/qgovec/gen.sh from vendor/quic-go — the reference's own code, run."
	echo " * Regenerate, do not edit. */"
	echo "#ifndef LC_QGO_VECTORS_H"
	echo "#define LC_QGO_VECTORS_H"
	echo "#include <stdint.h>"
	# Built with -c and run from here: `go test` would run the binary in the package's directory,
	# and internal/qgovec has none on disk. The generators carry the build tag qgovec, so nothing
	# but this compiles them: here they are four packages in one directory.
	printf '%s\n' "$pairs" | while read -r dir file; do
		bin="$tmp/$(echo "$dir" | tr / _).test"
		(cd "$q" && go test -c -vet=off -tags qgovec -overlay "$tmp/ov.json" -o "$bin" "./$dir")
		"$bin" -test.run '^TestQgoVec$' | grep -v -e '^PASS$'
	done
	echo "#endif"
} > "$tmp/out.h"
# A generator that failed prints its error into the pipe above and the grep passes it on; the
# header would then be garbage that compiles or not by chance. Every table must be there.
for t in qgo_cid_pkts qgo_ecn qgo_frame_close qgo_tp_close qgo_root_close qgo_flow qgo_pn_chrome qgo_pn_default qgo_initial_hdr_25 qgo_reno qgo_lost_order qgo_rtt qgo_skip_00 qgo_skip_ff qgo_stream_datalen; do
	grep -q "$t\[\]" "$tmp/out.h" || { echo "gen.sh: $t missing from the output:" >&2; cat "$tmp/out.h" >&2; exit 1; }
done
mv "$tmp/out.h" "$out"
