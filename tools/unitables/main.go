// The Unicode tables behind idna.Lookup as net/http runs it — GOROOT's own copies of x/net/idna and
// x/text (unicode/norm, unicode/bidi, secure/bidirule), Unicode 17.0.0 under Go 1.27 — written out for C, and the
// vectors that hold core/unorm.c, core/ubidi.c and core/idna.c to the real functions.
//
//	go run . tables  > build/gen/unitables.h
//	go run . vectors > build/gen/univec.h
//
// The packages are the ones Go ships in GOROOT/src/vendor, copied by the Makefile into
// tools/.goroot-x with one file added to each (lc_*.go.in here) that exports their tables. The
// trie thresholds — how many blocks of each trie are dense — are literals in the generated lookup
// code, so they are read from that code.
//
// The vectors are of two kinds. Checksums over every table lookup a C port can make: every rune,
// and every malformed sequence of the shapes the tries treat differently. And checksums over what
// the functions return for strings drawn from a pool of pieces chosen for what each one exercises,
// by a generator (splitmix64) that C runs the same way — plus the first strings in full, so that a
// mismatch can be read.
