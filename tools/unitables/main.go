func dense(file, trie string) int {
	src, err := os.ReadFile(file)
	if err != nil {
		panic(err)
	}
	re := regexp.MustCompile(`func \(t \*` + trie + `\) lookupValue\(n uint32, b byte\) uint(?:8|16) \{\s*switch \{\s*case n < (\d+):`)
	m := re.FindSubmatch(src)
	if m == nil {
		return -1 // every block dense: the switch has only its default
	}
	n, _ := strconv.Atoi(string(m[1]))
	return n
}

func u16s(name string, v []uint16) {
	fmt.Printf("static const uint16_t %s[%d] = {", name, len(v))
	for i, x := range v {
		if i%12 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" 0x%04x,", x)
	}
	fmt.Println("\n};")
}

func u8s(name string, v []byte) {
	fmt.Printf("static const uint8_t %s[%d] = {", name, len(v))
	for i, x := range v {
		if i%16 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" 0x%02x,", x)
	}
	fmt.Println("\n};")
}

func ranges(name string, v [][3]uint16) {
	fmt.Printf("static const lc_uni_range %s[%d] = {", name, len(v))
	for i, x := range v {
		if i%4 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" { 0x%04x, 0x%02x, 0x%02x },", x[0], x[1], x[2])
	}
	fmt.Println("\n};")
}

func tables(which string) {
	fmt.Println("/* Generated by tools/unitables from GOROOT's x/net/idna and x/text, Unicode " + unicode.Version + ". */")
	switch which {
	case "idna":
		idnaTables()
	case "nfc":
		nfcTables()
	case "bidi":
		bidiTables()
	default:
		panic(which)
	}
}

func idnaTables() {
	v, ix, so, sp, mi, maps, xor := idna.LCTables()
	fmt.Printf("#define IDNA_DENSE %d\n", dense("../.goroot-x/net/idna/tables"+unicode.Version+".go", "idnaTrie"))
	u16s("idna_values", v)
	u16s("idna_index", ix)
	u16s("idna_sparse_offset", so)
	ranges("idna_sparse", sp)
	u16s("idna_mapping_index", mi)
	u8s("idna_mappings", []byte(maps))
	u8s("idna_xor", []byte(xor))
}

func nfcTables() {
	nv, nix, nso, nsp, dec, cc, recomp, consts := norm.LCTables()
	fmt.Printf("#define NFC_DENSE %d\n", dense("../.goroot-x/text/unicode/norm/tables"+unicode.Version+".go", "nfcTrie"))
	for i, name := range []string{"FIRST_MULTI", "FIRST_CCC", "END_MULTI", "FIRST_LEADING_CCC",
		"FIRST_CCC_ZERO_EXCEPT", "FIRST_STARTER_WITH_NLEAD", "LAST_DECOMP", "MAX_DECOMP"} {
		fmt.Printf("#define NFC_%s 0x%x\n", name, consts[i])
	}
	u16s("nfc_values", nv)
	u8s("nfc_index", nix)
	u16s("nfc_sparse_offset", nso)
	ranges("nfc_sparse", nsp)
	u8s("nfc_decomps", dec)
	u8s("nfc_ccc", cc)
	// recompMap is a Go map filled from the packed pairs in order, so a key that came twice keeps
	// its last value; here it is a sorted array with the same answers.
	m := map[uint32]uint32{}
	for i := 0; i < len(recomp); i += 8 {
		b := []byte(recomp[i : i+8])
		m[uint32(b[0])<<24|uint32(b[1])<<16|uint32(b[2])<<8|uint32(b[3])] =
			uint32(b[4])<<24 | uint32(b[5])<<16 | uint32(b[6])<<8 | uint32(b[7])
	}
	keys := make([]uint32, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	fmt.Printf("static const uint32_t nfc_recomp[%d][2] = {", len(keys))
	for i, k := range keys {
		if i%4 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" { 0x%08x, 0x%05x },", k, m[k])
	}
	fmt.Println("\n};")
}

func bidiTables() {
	bv, bix := bidi.LCTables()
	if d := dense("../.goroot-x/text/unicode/bidi/tables"+unicode.Version+".go", "bidiTrie"); d != -1 {
		panic("the bidi trie has sparse blocks now")
	}
	u8s("bidi_values", bv)
	u16s("bidi_index", bix)
}

// ---- vectors --------------------------------------------------------------------------------------

type fnv uint64

func newFnv() fnv { return 14695981039346656037 }

func (h *fnv) bytes(b []byte) {
	for _, c := range b {
		*h ^= fnv(c)
		*h *= 1099511628211
	}
}

func (h *fnv) num(v uint64) {
	var b [8]byte
	for i := range b {
		b[i] = byte(v >> (8 * i))
	}
	h.bytes(b[:])
}

// The sequences every trie lookup is checked on: each rune's encoding — surrogates' too, as the
// three bytes a careless encoder writes — then every lead byte over every second byte, and the
// three- and four-byte shapes with the continuation bytes at and past their edges, whole and cut.
func sequences(f func([]byte)) {
	for r := 0; r <= 0x10FFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			f([]byte{byte(0xE0 | r>>12), byte(0x80 | (r>>6)&0x3F), byte(0x80 | r&0x3F)})
			continue
		}
		f([]byte(string(rune(r))))
	}
	edges := []byte{0x00, 0x41, 0x7F, 0x80, 0x9F, 0xA0, 0xBF, 0xC0, 0xFF}
	for c0 := 0x80; c0 <= 0xFF; c0++ {
		f([]byte{byte(c0)})
		for c1 := 0; c1 <= 0xFF; c1++ {
			f([]byte{byte(c0), byte(c1)})
		}
		for _, c1 := range edges {
			for _, c2 := range edges {
				f([]byte{byte(c0), c1, c2})
				for _, c3 := range edges {
					f([]byte{byte(c0), c1, c2, c3})
				}
			}
		}
	}
}

// splitmix64, which the C test runs the same way.
type rng uint64

func (s *rng) next() uint64 {
	*s += 0x9E3779B97F4A7C15
	z := uint64(*s)
	z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9
	z = (z ^ (z >> 27)) * 0x94D049BB133111EB
	return z ^ (z >> 31)
}

// The pieces a string is made of, each there for something: ASCII as it comes, dots of every kind,
// the ACE prefix and labels behind it, marks that reorder, compose, decompose, overflow the stream-
// safe limit, Hangul in all three shapes, right-to-left letters and numbers, joiners with the
// letters around them that allow them, mapped and ignored and disallowed runes, and bytes that are
// not UTF-8. The first `friendly` are ones a name that converts is made of: half the strings are
// drawn from those alone, so that the errors do not have the run of it.
var pool = []string{
	"a", "b", "z", "0", "9", "-", ".", "www", "example", "com", "xn--9ca", "xn--ww-cja",
	"\u00e9", "e\u0301", "\u0301", "\u0327", "\u0323", "\u0345", "\u0316", "\u1e0a\u0323", "\u00c5",
	"\u212b", "\u0041\u030a", "\u1100", "\u1161", "\u11a8", "\uac00", "\ud55c", "\u1100\u1161\u11a8",
	"\u05d0", "\u05d1", "\u0627", "\u0644", "\u0660", "\u06f0", "\u0628", "\u0915", "\u094d", "\u200c",
	"\u200d", "\uff21", "\u2160", "\u00df", "\u03c2", "\u3002", "\uff0e", "\u00ad", "\ufe0f", "\u1e9e",
	"\u0130", "\u2126", "\U0001d400", "A", "Z", "\u0958", "\u0f73", "\u0340", "\u0344", "\u2adc",
	// friendly ends here
	"--", "..", "_", " ", "xn--", "XN--", "xn--a", "xn--abc-", "xn--zzzz", "xn--99999999",
	"\U0001d160", strings.Repeat("\u0301", 31), strings.Repeat("\u0316\u0301", 9),
	"\u0661", "\u202e", "\u200f", "\uff61", "\U0001f600", "\ufffd", "\ue000", "\u0080", "\u00a0",
	"\u2028", "\U000e0001", "\U0010ffff", "\u0378",
	"\xff", "\xc3", "\xed\xa0\x80", "\xe0\x80\x80", "\xf4\x90\x80\x80", "\xc0\xaf", "\x80",
	// Compositions past U+FFFF, and Hangul at its edges: a later V, the T before the first, the
	// last syllable and the one after it.
	"\xf0\x91\x82\x99\xf0\x91\x82\xba", "\xf0\x91\x84\xb1\xf0\x91\x84\xa7", "\xf0\x91\x96\xb8\xf0\x91\x96\xaf",
	"\xe1\x84\x82\xe1\x85\xa5",
	"\xea\xb0\x80\xe1\x86\xa7", "\xea\xb0\x80\xe1\x86\xa8", "\xed\x9e\xa3", "\xed\x9e\xa4",
}

const friendly = 59

func draw(r *rng) string {
	var b strings.Builder
	n := int(r.next() % 13)
	m := uint64(len(pool))
	if r.next()&1 == 0 {
		m = friendly
	}
	for i := 0; i < n; i++ {
		b.WriteString(pool[r.next()%m])
	}
	return b.String()
}

func cstr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c == '"' || c == 92 {
			b.WriteByte(92)
			b.WriteByte(c)
		} else if c < 0x20 || c >= 0x7f || c == '?' {
			fmt.Fprintf(&b, "%c%03o", 92, c)
		} else {
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

const draws = 100000
const shown = 400

func vectors() {
	fmt.Println("/* Generated by tools/unitables from GOROOT's x/net/idna and x/text. */")

	hi, hn, hb, hp := newFnv(), newFnv(), newFnv(), newFnv()
	count := 0
	sequences(func(s []byte) {
		count++
		v, sz := idna.LCLookupString(string(s))
		hi.num(uint64(v)<<8 | uint64(sz))
		w, wz := norm.LCLookupString(string(s))
		hn.num(uint64(w)<<8 | uint64(wz))
		pr := norm.LCProps(string(s))
		for _, f := range pr {
			hp.num(uint64(f))
		}
		p, pz := bidi.LookupString(string(s))
		e, l := bidi.LCEntry(p)
		hb.num(uint64(e)<<16 | uint64(l)<<8 | uint64(pz))
		q, qz := bidi.Lookup(s)
		e, l = bidi.LCEntry(q)
		hb.num(uint64(e)<<16 | uint64(l)<<8 | uint64(qz))
	})
	fmt.Printf("#define UNIVEC_SEQUENCES %d\n", count)
	fmt.Printf("#define UNIVEC_IDNA_TRIE 0x%016xull\n", uint64(hi))
	fmt.Printf("#define UNIVEC_NFC_TRIE 0x%016xull\n", uint64(hn))
	fmt.Printf("#define UNIVEC_BIDI_TRIE 0x%016xull\n", uint64(hb))
	fmt.Printf("#define UNIVEC_NFC_PROPS 0x%016xull\n", uint64(hp))
	runes()
	named()

	fmt.Printf("static const char *const univec_pool[%d] = {", len(pool))
	for i, p := range pool {
		if i%6 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" %s,", cstr(p))
	}
	fmt.Println("\n};")
	fmt.Printf("static const unsigned univec_pool_len[%d] = {", len(pool))
	for i, p := range pool {
		if i%16 == 0 {
			fmt.Print("\n   ")
		}
		fmt.Printf(" %d,", len(p))
	}
	fmt.Println("\n};")

	// What each function returns for each drawn string, folded; the first `shown` in full.
	r := rng(0x6c632d756e69) // "lc-uni"
	hs := [6]fnv{newFnv(), newFnv(), newFnv(), newFnv(), newFnv(), newFnv()}
	errs, rtl := 0, 0
	fmt.Printf("#define UNIVEC_DRAWS %d\n", draws)
	fmt.Printf("#define UNIVEC_FRIENDLY %d\n", friendly)
	fmt.Printf("#define UNIVEC_SEED 0x%xull\n", uint64(r))
	fmt.Printf("static const struct { const char *in; const char *lookup; int lookup_err; const char *nfc; } univec_shown[%d] = {\n", shown)
	for i := 0; i < draws; i++ {
		s := draw(&r)
		a, err := idna.Lookup.ToASCII(s)
		e := 0
		if err != nil {
			e = 1
			errs++
			a = "" // what ToASCII returns beside an error is not used by anyone
		}
		hs[0].bytes([]byte(a))
		hs[0].num(uint64(e))
		nfc := norm.NFC.String(s)
		hs[1].bytes([]byte(nfc))
		hs[1].num(uint64(len(nfc)))
		hs[2].num(uint64(norm.NFC.QuickSpan([]byte(s))))
		n := uint64(0)
		if norm.NFC.IsNormalString(s) {
			n = 1
		}
		hs[3].num(n)
		v := uint64(0)
		if bidirule.ValidString(s) {
			v = 1
		}
		hs[4].num(v)
		d := uint64(0)
		if bidirule.DirectionString(s) == bidi.RightToLeft {
			d = 1
			rtl++
		}
		hs[5].num(d)
		if i < shown {
			fmt.Printf("    { %s, %s, %d, %s },\n", cstr(s), cstr(a), e, cstr(nfc))
		}
	}
	fmt.Println("};")
	for i, name := range []string{"LOOKUP", "NFC", "QUICKSPAN", "ISNORMAL", "BIDIRULE", "DIRECTION"} {
		fmt.Printf("#define UNIVEC_%s 0x%016xull\n", name, uint64(hs[i]))
	}
	fmt.Printf("#define UNIVEC_LOOKUP_ERRORS %d\n", errs)
	fmt.Printf("#define UNIVEC_RTL %d\n", rtl)
}


// Every rune in four places — alone; between two letters; between two dual-joining letters with a
// ZWNJ after it; after a consonant with a ZWJ after it — through Lookup.ToASCII, and alone and after
// a letter through NFC: what the tables say of each rune, as the functions use it, where the drawn
// strings reach only the runes in the pool.
func runes() {
	hl, hn := newFnv(), newFnv()
	errs := 0
	for r := rune(0); r <= 0x10FFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		c := string(r)
		for _, s := range []string{c, "a" + c + "b", "\xd8\xa8" + c + "\xe2\x80\x8c\xd8\xa8", "\xe0\xa4\x95" + c + "\xe2\x80\x8d"} {
			a, err := idna.Lookup.ToASCII(s)
			e := uint64(0)
			if err != nil {
				e = 1
				a = ""
				errs++
			}
			hl.bytes([]byte(a))
			hl.num(e)
		}
		for _, s := range []string{c, "a" + c} {
			n := norm.NFC.String(s)
			hn.bytes([]byte(n))
			hn.num(uint64(len(n)))
		}
	}
	fmt.Printf("#define UNIVEC_RUNES_LOOKUP 0x%016xull\n", uint64(hl))
	fmt.Printf("#define UNIVEC_RUNES_LOOKUP_ERRORS %d\n", errs)
	fmt.Printf("#define UNIVEC_RUNES_NFC 0x%016xull\n", uint64(hn))
}

// Names chosen for one rule each, with Go's answers in full: the joiners in and out of their
// contexts (RFC 5892 A.1, A.2), the Bidi Rule across labels — one of them decoded from xn-- —, a
// decoded label that is not NFC, the hyphen and mark rules, mappings and ignored runes.
func named() {
	ace := func(s string) string {
		a, err := idna.Punycode.ToASCII(s)
		if err != nil {
			panic(err)
		}
		return a
	}
	in := []string{
		"\xd8\xa8\xe2\x80\x8c\xd8\xa8", "\xd8\xa8\xe2\x80\x8c\xd8\xa7", "\xd8\xa8\xe2\x80\x8c", "a\xe2\x80\x8c",
		"\xd8\xa8\xd9\x8b\xe2\x80\x8c\xd8\xa8", "\xd8\xa8\xe2\x80\x8c\xd9\x8b\xd8\xa8", "\xd8\xa7\xe2\x80\x8c\xd8\xa8",
		"\xd8\xa8\xe2\x80\x8c\xd8\xa8\xe2\x80\x8c\xd8\xa8", "\xe2\x80\x8c\xd8\xa8", "\xd8\xa8\xe2\x80\x8c\xe2\x80\x8c\xd8\xa8",
		"\xe0\xa4\x95\xe0\xa5\x8d\xe2\x80\x8c\xe0\xa4\x95", "\xe0\xa4\x95\xe0\xa5\x8d\xe2\x80\x8d\xe0\xa4\x95",
		"\xe0\xa4\x95\xe2\x80\x8d", "\xe0\xa4\x95\xe0\xa5\x8d\xe2\x80\x8d", "\xe2\x80\x8d",
		// Mongolian joins both ways and runs left to right, so no Bidi Rule hides the joiners.
		"\xe1\xa0\xa0\xe2\x80\x8c", "\xe1\xa0\xa0\xe2\x80\x8c\xe1\xa0\xa0", "\xe1\xa0\xa0\xe2\x80\x8c\xe1\xa0\xa0\xe2\x80\x8c",
		"a\xe1\xa0\xa0\xe2\x80\x8cb",
		ace("e\xcc\x81"), ace("\xd7\x90") + ".1a", ace("\xd7\x90"), ace("\xd8\xa8\xe2\x80\x8c\xd8\xa8"),
		ace("a\xe2\x80\x8c"), ace("\xcc\x81a"), ace("\xef\xbc\xa1"), ace("\xc3\xa9") + "." + ace("\xd7\x90"),
		"ab--c", "abcd--e", "ab-", "-ab", "\xcc\x81a", "a\xcc\x81",
		"\xd7\x90.1a", "\xd7\x901", "1\xd7\x90", "\xd7\x90a", "a.\xd7\x90", "\xd9\xa0\xdb\xb0", "\xd7\x90\xcc\x81",
		"\xd8\xa8\xd9\xa0", "\xd8\xa8\xdb\xb0", "\xd7\x90-\xd7\x91", "\xd7\x90.\xd7\x91", "a\xd7\x90.b",
		"\xef\xbc\xa1\xe2\x85\xa0", "a\xc2\xadb", "ABC\xe3\x80\x82com", "\xe2\x84\xa6", "\xc3\x9f", "\xcf\x82",
		"\xe1\xba\x9e", "\xc4\xb0", "a\xef\xb8\x8fb", "\xe2\x91\xa0", "\xe3\x8c\x80",
	}
	fmt.Printf("static const struct { const char *in, *lookup; int err; } univec_named[%d] = {\n", len(in))
	for _, s := range in {
		a, err := idna.Lookup.ToASCII(s)
		e := 0
		if err != nil {
			e = 1
			a = ""
		}
		fmt.Printf("    { %s, %s, %d },\n", cstr(s), cstr(a), e)
	}
	fmt.Println("};")
}
func main() {
	if len(os.Args) < 2 {
		panic("tables idna|nfc|bidi, or vectors")
	}
	switch os.Args[1] {
	case "tables":
		tables(os.Args[2])
	case "vectors":
		vectors()
	default:
		panic(os.Args[1])
	}
}
