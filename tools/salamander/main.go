// Emits Salamander obfuscation vectors from the vendored hysteria itself — every packet of the
// Hysteria2 plane goes through this transform, and until 2026-09-01 nothing in the tree asked
// src/quic/obfs.c anything at all.
//
// THE REFERENCE IS RUN, NOT RESTATED. It would be a page less code to compute
// BLAKE2b-256(psk || salt) here and XOR by hand, and that page is exactly the one that must not be
// written: a generator that reimplements the thing it is checking produces vectors that agree with
// the reimplementation. So the packets below come out of obfs.WrapPacketConnSalamander through a
// PacketConn that does nothing but keep what it was handed — the same call the reference client
// makes, reaching salamanderObfuscator.Obfuscate by the same path.
//
// The salt is NOT ours to choose: the reference draws it from its own RandSrc, so each vector
// records whatever salt came out. That is the right way round anyway — the test's job is to
// deobfuscate a packet this client did not construct.
package main

import (
	"fmt"
	"io"
	"math"
	"math/rand"
	"net"
	"os"
	"time"

	"github.com/apernet/hysteria/extras/v2/obfs"
)

// A PacketConn that only remembers. Deliberately NOT a *net.UDPConn: wrapPacketConn checks for
// udpLikePacketConn and takes a different branch for one, and the branch this needs is the plain
// obfsPacketConn whose WriteTo obfuscates into its own buffer
// (vendor/hysteria/extras/obfs/conn.go:56-70, obfs/conn.go:90-99 — the path is kept on one line
// because a citation broken across two is one no checker can resolve).
type capture struct{ last []byte }

type addr struct{}

func (addr) Network() string { return "udp" }
func (addr) String() string  { return "127.0.0.1:1" }

func (c *capture) WriteTo(p []byte, _ net.Addr) (int, error) {
	c.last = append([]byte(nil), p...)
	return len(p), nil
}
func (c *capture) ReadFrom([]byte) (int, net.Addr, error) { return 0, nil, io.EOF }
func (c *capture) Close() error                           { return nil }
func (c *capture) LocalAddr() net.Addr                    { return addr{} }
func (c *capture) SetDeadline(time.Time) error            { return nil }
func (c *capture) SetReadDeadline(time.Time) error        { return nil }
func (c *capture) SetWriteDeadline(time.Time) error       { return nil }

func emit(name string, b []byte) {
	fmt.Printf("static const unsigned char %s[] = {", name)
	for i, v := range b {
		if i%12 == 0 {
			fmt.Printf("\n    ")
		}
		fmt.Printf("0x%02x, ", v)
	}
	if len(b) == 0 {
		fmt.Printf("0")
	}
	fmt.Printf("\n};\n")
	fmt.Printf("static const unsigned int  %s_len = %d;\n", name, len(b))
}

// The salt stream, for test/obfs/reference_gorand.h. salamanderObfuscator's RandSrc is unexported
// and seeded from the clock, so the obfuscator itself cannot be asked for a known stream; what it
// calls can. This makes exactly its two calls — `rand.New(rand.NewSource(seed))` once, then
// `Read(out[:smSaltLen])` per packet (vendor/hysteria/extras/obfs/salamander.go:43 and :65) — on the
// math/rand of the toolchain the reference is built with, for seeds that reach every branch of Seed:
// a clock-sized one, zero, the int32max that folds to zero, both signs and the int64 floor.
func emitGorand() {
	seeds := []int64{1758612345678901234, 0, 1, -1, math.MaxInt32, math.MaxInt32 + 1, math.MinInt64, 89482311}
	const salts = 8
	fmt.Println("/* Generated by tools/salamander (`go run . gorand`) from Go's own math/rand. */")
	fmt.Println("#ifndef LC_GORAND_VECTORS_H")
	fmt.Println("#define LC_GORAND_VECTORS_H")
	fmt.Println()
	fmt.Printf("#define GORAND_CASES %d\n", len(seeds))
	fmt.Printf("#define GORAND_SALTS %d\n\n", salts)
	fmt.Println("static const struct {")
	fmt.Println("    long long     seed;")
	fmt.Printf("    unsigned char stream[%d];\n", salts*8)
	fmt.Println("} gorand_cases[GORAND_CASES] = {")
	for _, seed := range seeds {
		r := rand.New(rand.NewSource(seed))
		var stream []byte
		for i := 0; i < salts; i++ {
			salt := make([]byte, 8)
			_, _ = r.Read(salt)
			stream = append(stream, salt...)
		}
		if seed == math.MinInt64 {
			fmt.Printf("    { -9223372036854775807LL - 1, {")
		} else {
			fmt.Printf("    { %dLL, {", seed)
		}
		for i, v := range stream {
			if i%12 == 0 {
				fmt.Printf("\n        ")
			}
			fmt.Printf("0x%02x, ", v)
		}
		fmt.Printf("\n    } },\n")
	}
	fmt.Println("};")
	fmt.Println()
	fmt.Println("#endif")
}

func main() {
	if len(os.Args) > 1 && os.Args[1] == "gorand" {
		emitGorand()
		return
	}
	fmt.Println("/* Generated by tools/salamander from vendor/hysteria's own obfuscator. */")
	fmt.Println("#ifndef LC_SALAMANDER_VECTORS_H")
	fmt.Println("#define LC_SALAMANDER_VECTORS_H")
	fmt.Println()

	// Passwords: the four-byte floor the reference refuses below, and a longer one, because the key
	// input is `psk || salt` and its length moves with the password — a fixed offset for the salt
	// would pass the short case and fail the long one.
	psks := []string{"psk1", "a-much-longer-obfuscation-password"}

	// Lengths chosen around the key period. The XOR indexes `key[i%32]`, so 31/32/33 and 63/64/65
	// are where an off-by-one in the wrap-around lives, and 0 is the empty body the reference still
	// obfuscates into a bare salt.
	lens := []int{0, 1, 31, 32, 33, 64, 65, 200, 1200}

	n := 0
	for _, psk := range psks {
		for _, l := range lens {
			plain := make([]byte, l)
			for j := range plain {
				plain[j] = byte(j*31%251 + 1)
			}
			// The capture lives behind the wrapper, so it is reached by writing and then reading
			// what the stub kept. A fresh wrapper per password keeps keyInput sized to that psk.
			cc := &capture{}
			p2, err := obfs.WrapPacketConnSalamander(cc, []byte(psk))
			if err != nil {
				panic(err)
			}
			if _, err := p2.WriteTo(plain, addr{}); err != nil {
				panic(err)
			}
			fmt.Printf("static const char          sal_psk_%d[] = %q;\n", n, psk)
			emit(fmt.Sprintf("sal_plain_%d", n), plain)
			emit(fmt.Sprintf("sal_wire_%d", n), cc.last)
			fmt.Println()
			n++
		}
	}

	fmt.Printf("#define SAL_CASES %d\n\n", n)
	fmt.Println("static const struct {")
	fmt.Println("    const char          *psk;")
	fmt.Println("    const unsigned char *plain;")
	fmt.Println("    unsigned int         plain_len;")
	fmt.Println("    const unsigned char *wire;")
	fmt.Println("    unsigned int         wire_len;")
	fmt.Println("} sal_cases[SAL_CASES] = {")
	for i := 0; i < n; i++ {
		fmt.Printf("    { sal_psk_%d, sal_plain_%d, sal_plain_%d_len, sal_wire_%d, sal_wire_%d_len },\n",
			i, i, i, i, i)
	}
	fmt.Println("};")
	fmt.Println()
	fmt.Println("#endif")
}
