// Run the pinned Xray Vision reader/writer and capture when outer alerts are suppressed.
package main

import (
	"bytes"
	"context"
	"fmt"
	"net"
	"os"

	"github.com/xtls/xray-core/common/buf"
	"github.com/xtls/xray-core/proxy"
)

type observedConn struct {
	net.Conn
	suppressed bool
}

func (c *observedConn) SuppressCloseNotify()        { c.suppressed = true }
func (c *observedConn) Write(p []byte) (int, error) { return len(p), nil }

func observe(direction int) bool {
	a, b := net.Pipe()
	defer a.Close()
	defer b.Close()
	c := &observedConn{Conn: a}
	id := make([]byte, 16)
	state := proxy.NewTrafficState(id)
	state.NumberOfPacketToFilter = 0
	if direction == 0 {
		frame := append(append([]byte{}, id...), 2, 0, 0, 0, 0)
		input := &bytes.Reader{}
		raw := &bytes.Buffer{}
		reader := proxy.NewVisionReader(buf.NewReader(bytes.NewReader(frame)), state,
			false, context.Background(), c, input, &raw, nil)
		mb, err := reader.ReadMultiBuffer()
		buf.ReleaseMulti(mb)
		if err != nil {
			panic(err)
		}
	} else {
		state.Outbound.IsPadding = false
		state.Outbound.UplinkWriterDirectCopy = true
		writer := proxy.NewVisionWriter(buf.Discard, state, true, context.Background(), c, nil, nil)
		if direction == 1 {
			if err := writer.WriteMultiBuffer(nil); err != nil {
				panic(err)
			}
		}
	}
	return c.suppressed
}

func main() {
	if len(os.Args) != 2 {
		panic("expected output header path")
	}
	var policy [3]int
	for direction := range policy {
		if observe(direction) {
			policy[direction] = 1
		}
	}
	header := fmt.Sprintf("/* Generated by tools/visionclose from the pinned Xray Vision implementation. */\n"+
		"static const int reference_suppresses_close_notify[3] = {%d, %d, %d};\n", policy[0], policy[1], policy[2])
	if err := os.WriteFile(os.Args[1], []byte(header), 0644); err != nil {
		panic(err)
	}
}
