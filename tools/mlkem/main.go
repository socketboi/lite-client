// Interop vectors for ML-KEM-768, produced by Go's crypto/mlkem.
//
// mlkem-native ships its own known-answer tests, but they are tied to its test RNG and only prove
// it agrees with itself. What the client actually needs to be sure of is different: that it
// decapsulates what the SERVER produces, and the server side of this product is Go. So the vectors
// come from the implementation on the other end of the wire.
//
// A seed is used rather than a generated key pair because FIPS 203 defines key generation from the
// 64-byte (d || z) seed, and both implementations expose exactly that — which makes the encapsulation
// key itself comparable, not just the shared secret derived from it.
//
//	go run ./tools/mlkem > build/gen/mlkem_vectors.h
package main

import (
	"crypto/mlkem"
	"crypto/rand"
	"fmt"
	"os"
)

func emit(name string, b []byte) {
	fmt.Printf("static const uint8_t %s[] = {", name)
	for i, x := range b {
		if i > 0 {
			fmt.Print(",")
		}
		if i%12 == 0 {
			fmt.Print("\n    ")
		}
		fmt.Printf("0x%02x", x)
	}
	fmt.Println("\n};")
}

func main() {
	seed := make([]byte, mlkem.SeedSize)
	if _, err := rand.Read(seed); err != nil {
		fmt.Fprintln(os.Stderr, "no randomness:", err)
		os.Exit(1)
	}

	dk, err := mlkem.NewDecapsulationKey768(seed)
	if err != nil {
		fmt.Fprintln(os.Stderr, "key generation from seed failed:", err)
		os.Exit(1)
	}
	ek := dk.EncapsulationKey()

	// Encapsulation is the server's move: it holds our encapsulation key and returns a ciphertext.
	// The client never runs this, which is exactly why it is the interesting direction to test.
	sharedSecret, ciphertext := ek.Encapsulate()

	fmt.Println("/* Generated by tools/mlkem, using Go's crypto/mlkem — the implementation this")
	fmt.Println(" * client has to interoperate with. Regenerate to get a fresh set; the values are")
	fmt.Println(" * arbitrary, what matters is that both sides derive the same secret from them. */")
	fmt.Println("#ifndef LC_MLKEM_VECTORS_H")
	fmt.Println("#define LC_MLKEM_VECTORS_H")
	fmt.Println()
	fmt.Println("#include <stdint.h>")
	fmt.Println()
	emit("mlkem768_seed", seed)
	emit("mlkem768_encapsulation_key", ek.Bytes())
	emit("mlkem768_ciphertext", ciphertext)
	emit("mlkem768_shared_secret", sharedSecret)

	// And ML-KEM-1024, which a Go 1.26 client keys only for the hybrid a server asks for in a retry,
	// SecP384r1MLKEM1024. Its own seed, so the two sets share nothing.
	seed1024 := make([]byte, mlkem.SeedSize)
	if _, err := rand.Read(seed1024); err != nil {
		fmt.Fprintln(os.Stderr, "no randomness:", err)
		os.Exit(1)
	}
	dk1024, err := mlkem.NewDecapsulationKey1024(seed1024)
	if err != nil {
		fmt.Fprintln(os.Stderr, "key generation from seed failed:", err)
		os.Exit(1)
	}
	ss1024, ct1024 := dk1024.EncapsulationKey().Encapsulate()
	emit("mlkem1024_seed", seed1024)
	emit("mlkem1024_encapsulation_key", dk1024.EncapsulationKey().Bytes())
	emit("mlkem1024_ciphertext", ct1024)
	emit("mlkem1024_shared_secret", ss1024)
	fmt.Println()
	fmt.Println("#endif")
}
