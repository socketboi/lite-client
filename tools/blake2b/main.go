// Emits BLAKE2b test vectors from golang.org/x/crypto — the implementation on the other end of the
// wire, since Hysteria is written in Go. Our own known-answer tests would only prove we agree with
// ourselves.
package main

import (
	"fmt"

	"golang.org/x/crypto/blake2b"
)

func main() {
	fmt.Println("/* Generated by tools/blake2b from golang.org/x/crypto/blake2b. */")
	fmt.Println("#ifndef LC_BLAKE2B_VECTORS_H")
	fmt.Println("#define LC_BLAKE2B_VECTORS_H")
	fmt.Println()

	// Lengths chosen around the block boundary, which is where a hash implementation goes wrong:
	// empty, short, exactly one block, one over, two blocks, and the size Salamander actually uses
	// (a password plus eight bytes of salt).
	for i, n := range []int{0, 1, 63, 127, 128, 129, 255, 256, 40} {
		in := make([]byte, n)
		for j := range in {
			in[j] = byte(j * 7 % 251)
		}
		sum := blake2b.Sum256(in)
		fmt.Printf("static const unsigned char b2b_in_%d[] = {", i)
		for j, b := range in {
			if j%12 == 0 {
				fmt.Printf("\n    ")
			}
			fmt.Printf("0x%02x, ", b)
		}
		if n == 0 {
			fmt.Printf("0")
		}
		fmt.Printf("\n};\n")
		fmt.Printf("static const unsigned int  b2b_in_%d_len = %d;\n", i, n)
		fmt.Printf("static const unsigned char b2b_out_%d[32] = {", i)
		for j, b := range sum {
			if j%12 == 0 {
				fmt.Printf("\n    ")
			}
			fmt.Printf("0x%02x, ", b)
		}
		fmt.Printf("\n};\n\n")
	}

	fmt.Println("#define LC_BLAKE2B_CASES 9")
	fmt.Println("#endif")
}
