// ML-DSA CertificateVerify fixtures for the Xray uTLS Go 1.27 reference.
// auth.go verifies the raw RFC 8446 signing input with crypto/mldsa.Verify.
// Fixed test seeds are not deployment credentials.
package main

import (
	"bytes"
	"crypto/ed25519"
	"crypto/mldsa"
	"crypto/x509"
	"crypto/x509/pkix"
	"fmt"
	"math/big"
	"time"
)

func emit(name string, value []byte) {
	fmt.Printf("static const unsigned char %s[] = {", name)
	for i, b := range value {
		if i%16 == 0 {
			fmt.Print("\n    ")
		}
		fmt.Printf("0x%02x,", b)
	}
	fmt.Println("\n};")
}

func main() {
	fmt.Println("/* Generated by tools/mldsacv with Go 1.27 crypto/mldsa and crypto/x509. */")
	th := make([]byte, 32)
	for i := range th {
		th[i] = byte(i*7 + 1)
	}
	content := append(bytes.Repeat([]byte{' '}, 64), []byte("TLS 1.3, server CertificateVerify\x00")...)
	content = append(content, th...)
	issuer := ed25519.NewKeyFromSeed(bytes.Repeat([]byte{42}, ed25519.SeedSize))
	template := &x509.Certificate{SerialNumber: big.NewInt(1),
		Subject:   pkix.Name{CommonName: "stand.local"},
		NotBefore: time.Unix(0, 0), NotAfter: time.Unix(1<<31-1, 0)}
	params := []mldsa.Parameters{mldsa.MLDSA44(), mldsa.MLDSA65(), mldsa.MLDSA87()}
	fmt.Println("struct mcv_case { const unsigned char *cert, *body; unsigned cert_len, body_len; const char *error; };")
	var rows []string
	for i, p := range params {
		key, err := mldsa.NewPrivateKey(p, bytes.Repeat([]byte{byte(i + 1)}, 32))
		must(err)
		cert, err := x509.CreateCertificate(nil, template, template, key.PublicKey(), issuer)
		must(err)
		// Also prove the certificate parser exposes the same public key the verifier uses.
		parsed, err := x509.ParseCertificate(cert)
		must(err)
		pub := parsed.PublicKey.(*mldsa.PublicKey)
		sig, err := key.SignDeterministic(content, nil)
		must(err)
		other, err := mldsa.NewPrivateKey(p, bytes.Repeat([]byte{99}, 32))
		must(err)
		wrong, err := other.SignDeterministic(content, nil)
		must(err)
		altered := bytes.Clone(sig)
		altered[len(altered)/2] ^= 1
		badContext, err := key.SignDeterministic(append([]byte("wrong context"), th...), nil)
		must(err)
		certName := fmt.Sprintf("mcv_cert_%d", i)
		emit(certName, cert)
		for j, s := range [][]byte{sig, altered, sig[:len(sig)-1], wrong, badContext} {
			verdict := mldsa.Verify(pub, content, s, nil)
			goError := ""
			if verdict != nil {
				goError = "tls: invalid signature by the server certificate: ML-DSA verification failure: " + verdict.Error()
			}
			// uTLS maps all three schemes to signatureMLDSA and verifies using the
			// key's own parameter set (vendor/utls/auth.go:49-58), including a
			// scheme with a different ML-DSA parameter name.
			for k := 0; k < 3; k++ {
				name := fmt.Sprintf("mcv_body_%d_%d_%d", i, j, k)
				body := append([]byte{9, byte(4 + k), byte(len(s) >> 8), byte(len(s))}, s...)
				emit(name, body)
				rows = append(rows, fmt.Sprintf("    {%s, %s, sizeof %s, sizeof %s, %q},",
					certName, name, certName, name, goError))
			}
		}
	}
	fmt.Println("static const struct mcv_case mcv_cases[] = {")
	for _, row := range rows {
		fmt.Println(row)
	}
	fmt.Println("};")
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
