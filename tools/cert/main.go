// Certificate vectors for the DER walk.
//
// REALITY takes exactly two things out of the server's leaf certificate: the ed25519 public key and
// the raw signature bytes. It then checks that the signature equals HMAC-SHA512 over the public key
// under a secret only the two ends know. The chain is never validated — it exists for whoever is
// watching, not for us.
//
// So the vectors are generated with Go's crypto/x509, and one of them is deliberately not a valid
// certificate at all: its signature field holds an HMAC instead of a signature, exactly as a REALITY
// server produces. A parser that insists on verifying what it reads would reject the very thing it
// is built to read.
//
//	go run ./tools/cert > build/gen/cert_vectors.h
package main

import (
	"crypto/ed25519"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha512"
	"crypto/x509"
	"crypto/x509/pkix"
	"fmt"
	"math/big"
	"os"
	"time"
)

func emit(name string, b []byte) {
	fmt.Printf("static const uint8_t %s[] = {", name)
	for i, x := range b {
		if i > 0 {
			fmt.Print(",")
		}
		if i%12 == 0 {
			fmt.Print("\n    ")
		}
		fmt.Printf("0x%02x", x)
	}
	fmt.Println("\n};")
}

func die(msg string, err error) {
	fmt.Fprintln(os.Stderr, msg+":", err)
	os.Exit(1)
}

func main() {
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		die("key generation", err)
	}

	// A minimal certificate: a REALITY server generates one on the fly for whatever name the
	// client asked for, so nothing here needs to be realistic beyond the shape.
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: "www.kinopoisk.ru"},
		NotBefore:    time.Unix(1700000000, 0),
		NotAfter:     time.Unix(1800000000, 0),
		DNSNames:     []string{"www.kinopoisk.ru"},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, pub, priv)
	if err != nil {
		die("certificate creation", err)
	}

	parsed, err := x509.ParseCertificate(der)
	if err != nil {
		die("re-parsing the certificate", err)
	}
	parsedPub, ok := parsed.PublicKey.(ed25519.PublicKey)
	if !ok {
		die("public key is not ed25519", fmt.Errorf("%T", parsed.PublicKey))
	}

	// The REALITY variant: the signature field carries HMAC-SHA512 over the public key. Both are
	// sixty-four bytes, so the DER structure is untouched — only the bytes inside change, which is
	// precisely why REALITY can do this without breaking any parser that does not verify.
	authKey := make([]byte, 32)
	if _, err := rand.Read(authKey); err != nil {
		die("no randomness", err)
	}
	mac := hmac.New(sha512.New, authKey)
	mac.Write(parsedPub)
	stamped := mac.Sum(nil)

	realityDER := append([]byte(nil), der...)
	sigStart := len(realityDER) - len(parsed.Signature)
	copy(realityDER[sigStart:], stamped)

	fmt.Println("/* Generated by tools/cert with Go's crypto/x509. The second certificate is what a")
	fmt.Println(" * REALITY server actually sends: same structure, but the signature field holds an")
	fmt.Println(" * HMAC over the public key rather than a signature. */")
	fmt.Println("#ifndef LC_CERT_VECTORS_H")
	fmt.Println("#define LC_CERT_VECTORS_H")
	fmt.Println()
	fmt.Println("#include <stdint.h>")
	fmt.Println()
	emit("cert_der", der)
	emit("cert_public_key", parsedPub)
	emit("cert_signature", parsed.Signature)
	fmt.Println()
	emit("reality_cert_der", realityDER)
	emit("reality_auth_key", authKey)
	emit("reality_cert_signature", stamped)
	fmt.Println()
	fmt.Println("#endif")
}
