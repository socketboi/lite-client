// Reference vectors for the REALITY stamp.
//
// The statements below are transcribed from the two implementations that define the protocol —
// vendor/Xray-core/transport/internet/reality/reality.go on the client side and
// vendor/REALITY/tls.go on the server side — deliberately kept in the same order and using the same
// standard-library calls. The point is that this file is not a paraphrase of how I read the
// protocol: if the C got the algorithm wrong because I misread it, this would have to be wrong in
// exactly the same way to agree, and it is not derived from the C at all.
//
// The vectors are generated with a fixed key, short id and timestamp so the sealed session_id is
// deterministic and can be compared byte for byte.
//
//	go run ./tools/reality > build/gen/reality_vectors.h
package main

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/hmac"
	"crypto/rand"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/binary"
	"fmt"
	"os"
	"regexp"
	"strconv"

	"golang.org/x/crypto/curve25519"
	"golang.org/x/crypto/hkdf"
)

func emit(name string, b []byte) {
	fmt.Printf("static const uint8_t %s[] = {", name)
	for i, x := range b {
		if i > 0 {
			fmt.Print(",")
		}
		if i%12 == 0 {
			fmt.Print("\n    ")
		}
		fmt.Printf("0x%02x", x)
	}
	fmt.Println("\n};")
}

func die(msg string, err error) {
	fmt.Fprintln(os.Stderr, msg+":", err)
	os.Exit(1)
}

func main() {
	// The server's static REALITY key pair, and the client's ephemeral one. Both ends derive the
	// same authentication key from opposite halves, which the vectors also check.
	serverPriv := make([]byte, 32)
	clientPriv := make([]byte, 32)
	if _, err := rand.Read(serverPriv); err != nil {
		die("no randomness", err)
	}
	if _, err := rand.Read(clientPriv); err != nil {
		die("no randomness", err)
	}
	serverPub, err := curve25519.X25519(serverPriv, curve25519.Basepoint)
	if err != nil {
		die("server public key", err)
	}
	clientPub, err := curve25519.X25519(clientPriv, curve25519.Basepoint)
	if err != nil {
		die("client public key", err)
	}

	// A ClientHello-shaped buffer. Only three things about it matter here: the random sits at
	// offset 6, session_id at 39, and the whole thing is the associated data.
	hello := make([]byte, 512)
	if _, err := rand.Read(hello); err != nil {
		die("no randomness", err)
	}
	hello[0] = 0x01
	const sidOff = 39
	random := hello[6:38]

	shortID := []byte{0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef}
	core, err := os.ReadFile("../../vendor/Xray-core/core/core.go")
	if err != nil {
		die("pinned Xray version", err)
	}
	version := make([]byte, 3)
	for i, field := range []string{"x", "y", "z"} {
		match := regexp.MustCompile(`Version_` + field + ` byte = ([0-9]+)`).FindSubmatch(core)
		if len(match) != 2 {
			panic("missing pinned Xray version field: " + field)
		}
		value, err := strconv.ParseUint(string(match[1]), 10, 8)
		if err != nil {
			die("pinned Xray version byte", err)
		}
		version[i] = byte(value)
	}
	const stamp = uint32(1754870400)

	// --- transcribed from reality.go, client side ---
	authKey, err := curve25519.X25519(clientPriv, serverPub)
	if err != nil {
		die("shared secret", err)
	}
	if _, err := hkdf.New(sha256.New, authKey, random[:20], []byte("REALITY")).Read(authKey); err != nil {
		die("hkdf", err)
	}
	block, err := aes.NewCipher(authKey)
	if err != nil {
		die("aes", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		die("gcm", err)
	}

	sessionID := make([]byte, 32)
	copy(hello[sidOff:], sessionID) // zeroed before it becomes associated data
	sessionID[0], sessionID[1], sessionID[2] = version[0], version[1], version[2]
	sessionID[3] = 0
	binary.BigEndian.PutUint32(sessionID[4:], stamp)
	copy(sessionID[8:], shortID)

	aead.Seal(sessionID[:0], random[20:], sessionID[:16], hello)
	copy(hello[sidOff:], sessionID)
	// --- end transcription ---

	// The certificate check: the signature field holds this HMAC over the certificate's public key.
	certPub := make([]byte, 32)
	if _, err := rand.Read(certPub); err != nil {
		die("no randomness", err)
	}
	mac := hmac.New(sha512.New, authKey)
	mac.Write(certPub)
	certSig := mac.Sum(nil)

	fmt.Println("/* Generated by tools/reality. The Go statements producing these values are")
	fmt.Println(" * transcribed from Xray-core's reality.go and REALITY's tls.go, so agreement here")
	fmt.Println(" * means agreement with the protocol rather than with a second reading of it. */")
	fmt.Println("#ifndef LC_REALITY_VECTORS_H")
	fmt.Println("#define LC_REALITY_VECTORS_H")
	fmt.Println()
	fmt.Println("#include <stdint.h>")
	fmt.Println()
	fmt.Printf("#define REALITY_VEC_SID_OFF %d\n", sidOff)
	fmt.Printf("#define REALITY_VEC_TIME %du\n", stamp)
	fmt.Println()
	emit("reality_vec_server_public", serverPub)
	emit("reality_vec_server_private", serverPriv)
	emit("reality_vec_client_private", clientPriv)
	emit("reality_vec_client_public", clientPub)
	emit("reality_vec_short_id", shortID)
	emit("reality_vec_version", version)
	emit("reality_vec_hello_stamped", hello)
	emit("reality_vec_auth_key", authKey)
	emit("reality_vec_cert_public", certPub)
	emit("reality_vec_cert_signature", certSig)
	fmt.Println()
	fmt.Println("#endif")
}
