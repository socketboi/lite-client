/* The two CompressedCertificate vectors Go cannot write.
 *
 * tools/chain produces the zlib one, because compress/zlib is in Go's standard library. brotli and
 * zstd are not, their Go ports are third-party modules, and `make check` runs with --network none —
 * so a generator that needed them would be a generator that cannot run in the gate. This one uses
 * the ENCODERS from the same vendored trees whose decoders the client links, which keeps the vector
 * and the thing it tests from sharing a bug only in the sense that matters: the encoder and the
 * decoder are different code paths, and a stream that round-trips through both is still a stream
 * whose format both ends agree on.
 *
 * ⚠️ AND THAT IS WEAKER THAN THE ZLIB VECTOR, WHICH IS WHY IT IS SAID HERE RATHER THAN DISCOVERED.
 * The zlib case is checked against an INDEPENDENT implementation — Go's, not libz's — so it proves
 * agreement about the format itself. These two prove that our decoder opens what upstream's own
 * encoder produced, which catches a wrong call, a wrong bound, a wrong length check, and would NOT
 * catch a shared misreading of the specification by brotli's authors. The live check in
 * test/certcomp/live.sh closes that for zstd against OpenSSL; for brotli nothing in this image
 * speaks it, and that gap is named in the test's own header.
 *
 * Built for the HOST, never for the target: it runs at build time and produces a header. */
#include "chain_vectors.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <brotli/encode.h>
#include <zstd.h>

/* RFC 8879: `algorithm(2) | uncompressed_length(3) | compressed<3>`, then the bytes. The same shape
 * tools/chain/main.go writes for zlib, spelled again here rather than shared, because sharing it
 * would mean a header this generator both writes and reads. */
static void emit(const char *name, unsigned algorithm, const unsigned char *plain, size_t plain_len,
                 const unsigned char *comp, size_t comp_len)
{
    printf("static const uint8_t %s[] = {\n   ", name);
    unsigned char head[8];
    head[0] = (unsigned char)(algorithm >> 8);
    head[1] = (unsigned char)algorithm;
    head[2] = (unsigned char)(plain_len >> 16);
    head[3] = (unsigned char)(plain_len >> 8);
    head[4] = (unsigned char)plain_len;
    head[5] = (unsigned char)(comp_len >> 16);
    head[6] = (unsigned char)(comp_len >> 8);
    head[7] = (unsigned char)comp_len;

    size_t n = 0;
    for (size_t i = 0; i < sizeof head; i++, n++)
        printf(" 0x%02x,%s", head[i], (n % 12 == 11) ? "\n   " : "");
    for (size_t i = 0; i < comp_len; i++, n++)
        printf(" 0x%02x,%s", comp[i], (n % 12 == 11) ? "\n   " : "");
    printf("\n};\n\n");
}

int main(void)
{
    printf("/* Generated by tools/certcomp/gen.c — do not edit.\n"
           " *\n"
           " * CompressedCertificate bodies for the two algorithms Go's standard library cannot\n"
           " * write, around the same certificate message tools/chain compresses with zlib. */\n\n");

    /* BROTLI_MAX_QUALITY rather than the default: a server choosing brotli is choosing it to save
     * bytes, and a vector compressed at quality 5 would exercise a different set of the decoder's
     * paths than the streams Cloudflare actually sends. LGWIN_MAX for the same reason. */
    size_t         bcap = BrotliEncoderMaxCompressedSize(sizeof certcomp_plain);
    unsigned char *bbuf = malloc(bcap);
    if (bbuf == NULL)
        return 1;
    size_t blen = bcap;
    if (!BrotliEncoderCompress(BROTLI_MAX_QUALITY, BROTLI_MAX_WINDOW_BITS, BROTLI_MODE_GENERIC,
                               sizeof certcomp_plain, certcomp_plain, &blen, bbuf)) {
        fprintf(stderr, "brotli refused to compress the fixture\n");
        return 1;
    }
    emit("certcomp_message_brotli", 2u, certcomp_plain, sizeof certcomp_plain, bbuf, blen);

    size_t         zcap = ZSTD_compressBound(sizeof certcomp_plain);
    unsigned char *zbuf = malloc(zcap);
    if (zbuf == NULL)
        return 1;
    size_t zlen = ZSTD_compress(zbuf, zcap, certcomp_plain, sizeof certcomp_plain,
                                ZSTD_maxCLevel());
    if (ZSTD_isError(zlen)) {
        fprintf(stderr, "zstd refused to compress the fixture: %s\n", ZSTD_getErrorName(zlen));
        return 1;
    }
    emit("certcomp_message_zstd", 3u, certcomp_plain, sizeof certcomp_plain, zbuf, zlen);

    free(bbuf);
    free(zbuf);
    return 0;
}
