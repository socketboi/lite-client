// CertificateVerify vectors: real certificates and real signatures over the real signing input.
//
// This message is the only proof that whoever answered our hello holds the private key of the
// certificate it sent. The REALITY plane once folded it into the transcript and checked nothing, so
// a prober could answer with any certificate and a signature of noise; the check exists now, and
// until test/certverify nothing asked it anything.
//
// ⚠️ A SUITE OF REFUSALS ALONE WOULD BE WORTHLESS HERE. Every negative case — a scheme we do not
// support, a truncated body, a signature of noise — is passed by a verifier that always says no, and
// "always says no" is not a failure anybody would notice in testing: handshakes would simply stop
// working, loudly, and someone would "fix" it by loosening the check. So the vectors below carry
// signatures that MUST verify, made with keys generated here, over the exact bytes RFC 8446 4.4.3
// names: sixty-four spaces, "TLS 1.3, server CertificateVerify", a zero byte, then the transcript
// hash.
//
// Signed by Go rather than by this client, which is the point: a vector this tree produced with the
// same code it is checking would agree with itself.
//
//	go run ./tools/certverify > build/gen/certverify_vectors.h

// Go refuses to make or use an RSA key under 1024 bits since 1.24 (GOROOT/src/crypto/rsa/rsa.go,
// checkKeySize); the one vector that needs such a key is made with that switched off here, so that
// the client can be shown refusing what Go, with the switch on as in both references, refuses.
//
//go:debug rsa1024min=0
package main

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/rsa"
	"crypto/ed25519"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/x509"
	"crypto/x509/pkix"
	"fmt"
	"math/big"
	"time"
)

const ctx = "TLS 1.3, server CertificateVerify"

// The transcript hash the vectors are built over. Fixed rather than random: a vector is a constant,
// and a constant that moves between runs is a diff nobody can read.
func transcript() []byte {
	h := make([]byte, 32)
	for i := range h {
		h[i] = byte(i*7 + 1)
	}
	return h
}

// RFC 8446 4.4.3, in full. The zero byte after the context is part of it and is the single most
// commonly dropped byte in an implementation of this message.
func signedContent(th []byte) []byte {
	b := make([]byte, 0, 64+len(ctx)+1+len(th))
	for i := 0; i < 64; i++ {
		b = append(b, 0x20)
	}
	b = append(b, []byte(ctx)...)
	b = append(b, 0x00)
	b = append(b, th...)
	return b
}

func leaf(pub, priv any) []byte {
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject:      pkix.Name{CommonName: "stand.local"},
		NotBefore:    time.Unix(0, 0),
		NotAfter:     time.Unix(1<<31-1, 0),
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, pub, priv)
	if err != nil {
		panic(err)
	}
	return der
}

func emit(name string, b []byte) {
	fmt.Printf("static const unsigned char %s[] = {", name)
	for i, v := range b {
		if i%12 == 0 {
			fmt.Printf("\n    ")
		}
		fmt.Printf("0x%02x, ", v)
	}
	if len(b) == 0 {
		fmt.Printf("0")
	}
	fmt.Printf("\n};\nstatic const unsigned int  %s_len = %d;\n", name, len(b))
}

// scheme || uint16 length || signature, which is the whole CertificateVerify body.
func body(scheme uint16, sig []byte) []byte {
	b := []byte{byte(scheme >> 8), byte(scheme), byte(len(sig) >> 8), byte(len(sig))}
	return append(b, sig...)
}

func main() {
	th := transcript()
	content := signedContent(th)

	fmt.Println("/* Generated by tools/certverify. Signatures made by Go, over RFC 8446 4.4.3 input. */")
	fmt.Println("#ifndef LC_CERTVERIFY_VECTORS_H")
	fmt.Println("#define LC_CERTVERIFY_VECTORS_H")
	fmt.Println()
	emit("cv_transcript", th)
	fmt.Println()

	// Ed25519 — the scheme a REALITY node uses, and the only one it offers.
	edPub, edPriv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	emit("cv_ed_cert", leaf(edPub, edPriv))
	emit("cv_ed_body", body(0x0807, ed25519.Sign(edPriv, content)))
	fmt.Println()

	// The same certificate, signed by a DIFFERENT key. Well formed in every way a parser can see,
	// and the one case that separates a verifier from a formality.
	_, otherPriv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	emit("cv_ed_body_wrongkey", body(0x0807, ed25519.Sign(otherPriv, content)))
	fmt.Println()

	// The same key over DIFFERENT content: a signature that is genuine and answers another question.
	// A verifier that hashes the wrong thing — dropping the zero byte, or the sixty-four spaces —
	// accepts this and rejects the real one.
	other := signedContent(make([]byte, 32))
	emit("cv_ed_body_otherhash", body(0x0807, ed25519.Sign(edPriv, other)))
	fmt.Println()

	// RSA, the third and last key kind the reference's type switch admits — present so the
	// classifier's YES column covers all three, not the two that happened to be lying around.
	rsaPriv, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		panic(err)
	}
	emit("cv_rsa_cert", leaf(&rsaPriv.PublicKey, rsaPriv))
	sum256 := sha256.Sum256(content)
	pss := &rsa.PSSOptions{SaltLength: rsa.PSSSaltLengthEqualsHash}
	rsaSig, err := rsa.SignPSS(rand.Reader, rsaPriv, crypto.SHA256, sum256[:], pss)
	if err != nil {
		panic(err)
	}
	emit("cv_rsa_body", body(0x0804, rsaSig))
	fmt.Println()

	// An RSA key of 768 bits and a signature by it that is good in every other way: what Go, since
	// 1.24, refuses in VerifyPSS before it looks at the signature.
	smallPriv, err := rsa.GenerateKey(rand.Reader, 768)
	if err != nil {
		panic(err)
	}
	smallSig, err := rsa.SignPSS(rand.Reader, smallPriv, crypto.SHA256, sum256[:], pss)
	if err != nil {
		panic(err)
	}
	emit("cv_rsa768_cert", leaf(&smallPriv.PublicKey, smallPriv))
	emit("cv_rsa768_body", body(0x0804, smallSig))
	fmt.Println()

	// ECDSA P-256, which signs a DIGEST of the same content rather than the content itself.
	ecPriv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		panic(err)
	}
	sum := sha256.Sum256(content)
	ecSig, err := ecdsa.SignASN1(rand.Reader, ecPriv, sum[:])
	if err != nil {
		panic(err)
	}
	emit("cv_ec_cert", leaf(&ecPriv.PublicKey, ecPriv))
	emit("cv_ec_body", body(0x0403, ecSig))

	fmt.Println()
	fmt.Println("#endif")
}
