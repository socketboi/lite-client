#include "quic/huffman_table.h"

/* ⚠️ A DIFFERENT ALGORITHM FOR THE SAME ANSWER, which is why this file cited nothing and the sieve
 * never opened it. The reference decodes with a generated 256-state transition machine, two nibble
 * steps per byte — `t = qpack_huffman_decode_table[t.fstate][c >> 4]`
 * (vendor/nghttp3/lib/nghttp3_qpack_huffman.c:105-111) — and its data file is 115 KB of source;
 * this walks bits against a 2 KB canonical table, for the reason tools/hpack/main.go
 * states at its head. So there is no line-for-line correspondence to point at, and what has to
 * agree is the OUTPUT and, more importantly, the ACCEPT/REFUSE rule. Both are pinned here.
 *
 * The symbols themselves are not read from the reference at run time, they are CUT from it: the
 * table this ships is generated by tools/hpack out of `huffman_sym_table`
 * (vendor/nghttp3/lib/nghttp3_qpack_huffman_data.c:30), so a value that changed there changes here
 * or the generator refuses.
 *
 * Where the two must not diverge is the end of a value, and BOTH HALVES ARE CITED AT THEIR OWN
 * CODE rather than here — the encoder's padding at the line that pads, the decoder's accept rule at
 * the line that decides. That placement is not tidiness: a citation standing in a header essay
 * hands a reader the reference and a page of prose, and the first four questions ever asked about
 * this file came back as "the encoder never pads" and "EOS is rejected in the wrong place", both
 * from reading the paragraph instead of the function. This file reaches the same two verdicts
 * arithmetically rather than through a state's flags.
 *
 * Decoding walks the input one bit at a time, which is the whole trick that makes the table small.
 *
 * The code is canonical: sort the symbols by (length, code) and, within each length, the codes run
 * consecutively from a known first value. So a code is recognised the moment `code - first` is less
 * than how many codes that length has — no tree to walk, no state machine to store, one comparison
 * per bit. tools/hpack checks that property against nghttp3's table and refuses to emit a table
 * that breaks it. */
long lc_huff_decode(const uint8_t *in, size_t len, char *out, size_t cap)
{
    size_t   written = 0, total = 0;
    uint32_t code = 0;
    unsigned bits = 0;

    for (size_t i = 0; i < len; i++) {
        for (int b = 7; b >= 0; b--) {
            code = code << 1 | (in[i] >> b & 1u);
            bits++;

            if (bits > LC_HUFF_MAX_BITS)
                return -1;
            if (bits < LC_HUFF_MIN_BITS || huff_count[bits] == 0)
                continue;
            if (code - huff_first_code[bits] >= huff_count[bits])
                continue;

            uint16_t sym = huff_ordered[huff_first_index[bits] + (code - huff_first_code[bits])];
            /* RFC 7541 section 5.2: a value that contains the end-of-string symbol is malformed.
             * Refused rather than stopped at, because a peer that emits it is not one whose framing
             * we still understand. */
            if (sym == LC_HUFF_EOS)
                return -1;

            if (written + 1u < cap)
                out[written++] = (char)sym;
            total++;

            code = 0;
            bits = 0;
        }
    }

    /* What is left over must be the beginning of the end-of-string code, which is all ones, and
     * must be shorter than a byte — anything else is either a truncated value or a coding we would
     * be guessing at.
     *
     * This is the ACCEPT/REFUSE rule, and it is the one thing that must match the reference
     * exactly: it refuses input that does not end on a symbol boundary, `if (fin && !(ctx->flags &
     * NGHTTP3_QPACK_HUFFMAN_FLAG_ACCEPTED)) return NGHTTP3_ERR_QPACK_FATAL;`
     * (vendor/nghttp3/lib/nghttp3_qpack_huffman.c:119-121), with an invalid code landing in a
     * failure state of its own (vendor/nghttp3/lib/nghttp3_qpack_huffman.c:126-129). Same two
     * verdicts, reached by arithmetic here and by a state's flags there; the error VALUE differs
     * and nothing on the wire depends on it. */
    if (bits >= 8u || (bits > 0 && code != ((uint32_t)1 << bits) - 1u))
        return -1;

    if (cap > 0)
        out[written < cap ? written : cap - 1u] = '\0';
    return (long)total;
}

size_t lc_huff_len(const char *in, size_t len)
{
    size_t bits = 0;
    for (size_t i = 0; i < len; i++)
        bits += huff_nbits[(uint8_t)in[i]];
    return (bits + 7u) / 8u;
}

long lc_huff_encode(const char *in, size_t len, uint8_t *out, size_t cap)
{
    size_t   n = 0;
    uint64_t acc = 0;
    unsigned bits = 0;

    for (size_t i = 0; i < len; i++) {
        uint8_t c = (uint8_t)in[i];
        acc = acc << huff_nbits[c] | huff_code[c];
        bits += huff_nbits[c];

        while (bits >= 8u) {
            if (n >= cap)
                return -1;
            bits -= 8u;
            out[n++] = (uint8_t)(acc >> bits);
        }
    }

    /* Padded to the byte with ones: the start of the end-of-string code, which is what a decoder
     * expects to find and stop at. The reference writes the same byte the same way —
     * `*dest++ = (uint8_t)((uint8_t)(code >> 56) | ((1 << (8 - nbits)) - 1))`
     * (vendor/nghttp3/lib/nghttp3_qpack_huffman.c:74) — and this is the line that has to agree with
     * it, which is why the citation is here and not in the header. */
    if (bits > 0) {
        if (n >= cap)
            return -1;
        out[n++] = (uint8_t)(acc << (8u - bits) | ((1u << (8u - bits)) - 1u));
    }
    return (long)n;
}
