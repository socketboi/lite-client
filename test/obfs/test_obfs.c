/* Salamander, against packets the reference produced.
 *
 * WHY THIS FILE EXISTS. src/quic/obfs.c transforms EVERY packet of the Hysteria2 plane, and until
 * 2026-09-01 nothing in this tree asked it anything — it was one of five modules under src/ that no
 * test linked. The transform is eight bytes of salt and an XOR by a repeated hash, which is small
 * enough to read and be sure of, and that is exactly the size of thing that gets read and believed
 * rather than run.
 *
 * ⚠️ AND A WRONG OBFUSCATOR DOES NOT LOOK WRONG. It is XOR with a key derived from a salt the sender
 * itself chose, so nothing here can tell a right password from a wrong one and nothing on the node
 * can either — a mismatch is not an error, it is a QUIC packet that fails to parse, which is
 * indistinguishable from a lost one. The failure mode is "the plane just does not come up", with no
 * line anywhere saying why.
 *
 * WHERE THE VECTORS COME FROM. reference_salamander.h is generated by tools/salamander, which does
 * NOT reimplement the transform: it calls obfs.WrapPacketConnSalamander on the vendored hysteria and
 * keeps what the wrapper wrote. So every `wire` below is a packet the reference actually emitted,
 * and the first assertion is this client deobfuscating a packet it did not construct.
 *
 * The header is FROZEN in the tree rather than regenerated by the build, and that is deliberate:
 * hysteria's module pulls forty dependencies, the offline gate has only a warm cache of a few, and
 * `make check` must keep running with --network none. Same arrangement, for the same reason, as
 * test/fphello/reference_firefox.h. To regenerate, with network:
 *
 *     cd tools/salamander && go mod tidy && go run . > ../../test/obfs/reference_salamander.h
 *
 * AND THE SALT. The reference draws it from Go's math/rand seeded with the clock, and the salt is
 * on the wire in the clear, so its stream is checked too: reference_gorand.h holds what
 * `rand.New(rand.NewSource(seed))` and eight-byte Reads give in Go, for seeds that reach every
 * branch of Seed. Regenerated the same way, with `go run . gorand > ../../test/obfs/reference_gorand.h`.
 */

#include "quic/obfs.h"
#include "quic/obfs.c"
#include "reference_gorand.h"

#include "reference_salamander.h"

#include <stdio.h>
#include <string.h>

static int fails;

static void ok(int cond, const char *what)
{
    if (cond) {
        printf("  ok    %s\n", what);
    } else {
        printf("  FAIL  %s\n", what);
        fails++;
    }
}

static uint8_t buf[4096];
static uint8_t buf2[4096];

/* THE CROSS-IMPLEMENTATION CASE, and the only one here that could not be passed by a self-consistent
 * mistake: the bytes were made by the reference and are unwrapped by us. A wrong salt length, a
 * wrong key length, a keyed BLAKE2b where the reference uses a plain one, or an off-by-one in the
 * `i % 32` wrap-around all fail here and nowhere else. */
static void test_against_reference(void)
{
    int all = 1, empties = 0;

    for (unsigned i = 0; i < SAL_CASES; i++) {
        lc_obfs o;
        if (lc_obfs_init(&o, sal_cases[i].psk) != 0) {
            printf("        case %u: the password was refused\n", i);
            all = 0;
            continue;
        }

        long n = lc_obfs_unwrap(&o, sal_cases[i].wire, sal_cases[i].wire_len, buf, sizeof buf);

        /* The reference OBFUSCATES an empty payload into a bare salt and then REFUSES to
         * deobfuscate it — `outLen := len(in) - smSaltLen` with `outLen <= 0` returning zero
         * (vendor/hysteria/extras/obfs/salamander.go:74-78). So the vector for a zero-length body is
         * a packet the reference itself would throw away, and the right answer here is a refusal
         * that agrees with it. Counted separately so that a suite which somehow saw only these
         * cannot look like a pass. */
        if (sal_cases[i].plain_len == 0u) {
            if (n != -1) {
                printf("        case %u: a bare salt was accepted; the reference refuses it\n", i);
                all = 0;
            }
            empties++;
            continue;
        }

        if (n != (long)sal_cases[i].plain_len) {
            printf("        case %u: got %ld bytes back, the reference put in %u\n", i, n,
                   sal_cases[i].plain_len);
            all = 0;
            continue;
        }
        if (memcmp(buf, sal_cases[i].plain, sal_cases[i].plain_len) != 0) {
            printf("        case %u: %u bytes came back different\n", i, sal_cases[i].plain_len);
            all = 0;
        }
    }

    ok(all, "every packet the reference obfuscated comes back as what went in");
    ok(empties == 2, "and the two bare salts are refused, exactly as the reference refuses them");
}

static void test_shape_and_round_trip(void)
{
    lc_obfs o;
    ok(lc_obfs_init(&o, "a-much-longer-obfuscation-password") == 0, "a password is accepted");

    static const uint8_t in[200] = { 1, 2, 3, 4 };
    long                 w = lc_obfs_wrap(&o, in, sizeof in, buf, sizeof buf);
    ok(w == (long)(sizeof in + LC_OBFS_SALT), "wrapping adds exactly the eight-byte salt");

    long u = lc_obfs_unwrap(&o, buf, (size_t)w, buf2, sizeof buf2);
    ok(u == (long)sizeof in && memcmp(buf2, in, sizeof in) == 0, "and unwrapping gives it back");

    /* ⚠️ A FRESH SALT EVERY PACKET, which is the whole reason the salt exists. With one fixed mask,
     * two packets XORed together cancel it and hand over the difference of their plaintexts — and
     * on a tunnel that difference is structure, not noise. A salt that did not advance would pass
     * every other assertion in this file. */
    long w2 = lc_obfs_wrap(&o, in, sizeof in, buf2, sizeof buf2);
    ok(w2 == w && memcmp(buf, buf2, LC_OBFS_SALT) != 0,
       "two packets of the same bytes carry different salts");
    ok(memcmp(buf + LC_OBFS_SALT, buf2 + LC_OBFS_SALT, sizeof in) != 0,
       "so the two bodies differ too, which is what the fresh salt is for");
}

/* The salt stream, against Go. First the generator on its own, for every seed the vectors carry —
 * the clock-sized one, zero, the int32max that folds to zero, both signs and the int64 floor — read
 * as the reference reads it, eight bytes a packet, so the seven-byte carry between Int63 values is
 * crossed on every other read. Then the same stream coming out of lc_obfs_wrap as the salts of eight
 * packets, which is the part a correct generator wired to nothing would miss. */
static void test_salt_stream(void)
{
    int all = 1;
    for (unsigned i = 0; i < GORAND_CASES; i++) {
        lc_gorand r;
        lc_gorand_seed(&r, (int64_t)gorand_cases[i].seed);
        for (unsigned k = 0; k < GORAND_SALTS; k++) {
            uint8_t salt[LC_OBFS_SALT];
            lc_gorand_read(&r, salt, sizeof salt);
            if (memcmp(salt, gorand_cases[i].stream + k * LC_OBFS_SALT, sizeof salt) != 0) {
                printf("        seed %lld, salt %u differs from Go's\n", gorand_cases[i].seed, k);
                all = 0;
                break;
            }
        }
    }
    ok(all, "every seed gives Go's math/rand salt stream, byte for byte");

    lc_obfs o;
    ok(lc_obfs_init(&o, "abcd") == 0, "a password is accepted");
    lc_gorand_seed(&o.salt, (int64_t)gorand_cases[0].seed);
    static const uint8_t in[40] = { 5, 6, 7 };
    int                  wired = 1;
    for (unsigned k = 0; k < GORAND_SALTS; k++) {
        long w = lc_obfs_wrap(&o, in, sizeof in, buf, sizeof buf);
        if (w != (long)(sizeof in + LC_OBFS_SALT) ||
            memcmp(buf, gorand_cases[0].stream + k * LC_OBFS_SALT, LC_OBFS_SALT) != 0)
            wired = 0;
    }
    ok(wired, "and the salts of eight wrapped packets are that stream, in order");
}

static void test_refusals(void)
{
    lc_obfs o;

    /* smPSKMinLen = 4 (vendor/hysteria/extras/obfs/salamander.go:14). Below it the reference returns
     * ErrPSKTooShort, and a password the node will not take must not be accepted quietly here: it
     * would produce the same silence as no obfuscation at all. */
    ok(lc_obfs_init(&o, "abc") != 0, "a three-byte password is refused, as the reference refuses it");
    ok(lc_obfs_init(&o, "abcd") == 0, "four is the floor, and four is accepted");

    /* Empty means OFF rather than an error — the plane runs without obfuscation by default. */
    lc_obfs off;
    ok(lc_obfs_init(&off, "") == 0, "an empty password is not an error");
    static const uint8_t in[16] = { 9, 8, 7 };
    long                 n = lc_obfs_wrap(&off, in, sizeof in, buf, sizeof buf);
    ok(n == (long)sizeof in && memcmp(buf, in, sizeof in) == 0,
       "with the obfuscator off the packet passes through untouched");
    ok(lc_obfs_init(&off, NULL) == 0, "and no password at all is the same as an empty one");

    lc_obfs on;
    (void)lc_obfs_init(&on, "abcd");
    ok(lc_obfs_unwrap(&on, buf, LC_OBFS_SALT, buf2, sizeof buf2) == -1,
       "a datagram of exactly the salt carries no body and is refused");
    ok(lc_obfs_unwrap(&on, buf, LC_OBFS_SALT + 1u, buf2, sizeof buf2) == 1,
       "one byte more is a body of one, and is not");

    /* The caller's buffer is asked about rather than assumed: this runs on a router, and the packet
     * being wrapped is bigger than the one that arrived. */
    ok(lc_obfs_wrap(&on, in, sizeof in, buf, sizeof in) == -1,
       "wrapping refuses a buffer with no room for the salt");
    ok(lc_obfs_unwrap(&on, buf, 100u, buf2, 10u) == -1, "unwrapping refuses one too small for the body");
}

int main(void)
{
    printf("Salamander, against packets the reference produced\n");

    test_against_reference();
    test_shape_and_round_trip();
    test_salt_stream();
    test_refusals();

    printf("\n%s\n", fails == 0 ? "this client obfuscates as hysteria obfuscates"
                                : "the obfuscation has DIVERGED from the reference");
    return fails == 0 ? 0 : 1;
}
